/*
 * ВОПРОС 1: Зачем нужен EXCEPT?
 * ОТВЕТ: EXCEPT вычитает одно множество из другого. Мы берём все пиццерии,
 *        которые Андрей посещал, и вычитаем те, откуда он делал заказы.
 *        Результат: посещал, но не заказывал.
 * 
 * ВОПРОС 2: Почему во втором запросе 4 таблицы, а в первом 3?
 * ОТВЕТ: person_visits напрямую связана с pizzeria (person_visits.pizzeria_id).
 *        person_order не имеет прямой связи с pizzeria — нужно идти через menu
 *        (person_order → menu → pizzeria). Поэтому нужен дополнительный JOIN.
 * 
 * ВОПРОС 3: Что означает ORDER BY 1?
 * ОТВЕТ: Сортировка по первой колонке в SELECT (pizzeria_name).
 *        Это то же самое, что ORDER BY pizzeria_name.
 * 
 * ВОПРОС 4: Зачем алиасы visit, client, ord, pizz?
 * ОТВЕТ: Улучшают читаемость кода. Короткие имена удобнее писать в JOIN условиях.
 *        Также помогают различать таблицы при множественных JOIN'ах.
 * 
 * ВОПРОС 5: Может ли результат быть пустым?
 * ОТВЕТ: Да, если Андрей делал заказы из ВСЕХ пиццерий, которые посещал.
 *        Тогда A EXCEPT B = {} (пустое множество).
 * 
 * ВОПРОС 6: EXCEPT убирает дубликаты?
 * ОТВЕТ: Да, EXCEPT автоматически применяет DISTINCT.
 *        Если Андрей посетил Best Pizza 5 раз, но не заказывал — 
 *        в результате будет только 1 строка 'Best Pizza'.
 * 
 * ВОПРОС 7: Почему не использовать LEFT JOIN?
 * ОТВЕТ: Можно, но EXCEPT проще и читаемее для этой задачи.
 *        LEFT JOIN потребует больше условий и проверок на NULL.
 *        EXCEPT декларативно выражает логику "A без B".
 */

