/*
 * ЗАДАЧА:
 * Найти все пиццерии, которые посещал Андрей, но из которых он НЕ делал заказов.
 * 
 * ЛОГИКА:
 * - Берём ВСЕ пиццерии, где был Андрей (person_visits)
 * - Вычитаем пиццерии, откуда он делал заказы (person_order + menu)
 * - Результат: пиццерии, где он был, но ничего не заказал
 * 
 * КЛЮЧЕВОЙ ОПЕРАТОР: EXCEPT (вычитание множеств)
 * - A EXCEPT B = элементы из A, которых НЕТ в B
 */

-- ============================================================================
-- ЧАСТЬ 1: Все пиццерии, которые посещал Андрей
-- ============================================================================

SELECT pizz.name AS pizzeria_name
-- ↑↑↑
-- КОММЕНТАРИЙ: Выбираем название пиццерии
-- - AS pizzeria_name: алиас для результата (единообразие с EXCEPT)
-- - pizz.name: название из таблицы pizzeria

FROM person_visits visit
-- ↑↑↑
-- КОММЕНТАРИЙ: Таблица посещений (журнал визитов клиентов)
-- - visit: алиас для person_visits
-- - Содержит: person_id, pizzeria_id, visit_date
-- - Это ОСНОВНАЯ таблица для первого запроса (посещения)
-- 
-- ПРИМЕР ДАННЫХ:
-- ┌────────────────┬───────────────┬────────────┐
-- │ id  │ person_id │ pizzeria_id   │ visit_date │
-- ├─────┼───────────┼───────────────┼────────────┤
-- │ 4   │ 2 (Andrey)│ 5 (Best Pizza)│ 2022-01-01 │
-- │ 5   │ 2 (Andrey)│ 6 (DinoPizza) │ 2022-01-02 │
-- └─────┴───────────┴───────────────┴────────────

INNER JOIN person client 
    ON client.id = visit.person_id
-- ↑↑↑
-- КОММЕНТАРИЙ: Присоединяем таблицу person для фильтрации по имени
-- - client.id = visit.person_id: связываем посещение с конкретным человеком
-- - INNER JOIN: берём только существующих клиентов (не может быть NULL)
-- - Алиас 'client' улучшает читаемость (понятно, что речь о клиенте)
-- 
-- ПОТОК ДАННЫХ:
--   person_visits (person_id=2)
--   ↓ JOIN
--   person (id=2, name='Andrey', gender='male')
--   ↓
--   Результат: посещения только для Andrey

INNER JOIN pizzeria pizz 
    ON pizz.id = visit.pizzeria_id
-- ↑↑↑
-- КОММЕНТАРИЙ: Присоединяем таблицу pizzeria для получения названия
-- - visit.pizzeria_id = pizz.id: связываем посещение с пиццерией
-- - Получаем название пиццерии вместо ID
-- 
-- ПОТОК ДАННЫХ:
--   person_visits (pizzeria_id=5)
--   ↓ JOIN
--   pizzeria (id=5, name='Best Pizza')
--   ↓
--   Результат: 'Best Pizza'

WHERE client.name = 'Andrey'
-- ↑↑↑
-- КОММЕНТАРИЙ: Фильтруем только посещения Андрея
-- - name = 'Andrey': оставляем только этого клиента
-- - Все посещения других людей исключаются
-- 
-- ПРИМЕР ДАННЫХ ПОСЛЕ ФИЛЬТРА:
-- ┌─────────────────┐
-- │ pizzeria_name   │
-- ├─────────────────┤
-- │ Best Pizza      │  ← Андрей посетил 01.01.2022
-- │ DinoPizza       │  ← Андрей посетил 02.01.2022
-- └─────────────────┘

-- ============================================================================
-- ОПЕРАТОР EXCEPT: Вычитание множеств
-- ============================================================================

EXCEPT
-- ↑↑↑
-- КОММЕНТАРИЙ: Оператор вычитания множеств (Set Difference)
-- 
-- МАТЕМАТИКА: A \ B = {x | x ∈ A и x ∉ B}
-- - A: пиццерии, которые Андрей ПОСЕЩАЛ
-- - B: пиццерии, откуда Андрей ДЕЛАЛ ЗАКАЗЫ
-- - Результат: посещал, но НЕ заказывал
-- 
-- КЛЮЧЕВЫЕ ОСОБЕННОСТИ:
-- - Автоматически убирает дубликаты (DISTINCT)
-- - Требует одинаковое количество колонок в обоих SELECT
-- - Типы данных должны быть совместимы
-- - Порядок важен: A EXCEPT B ≠ B EXCEPT A
-- 
-- ПРИМЕР РАБОТЫ:
--   Посещения (A):     {Best Pizza, DinoPizza}
--   Заказы (B):        {Best Pizza}
--   
--   Результат A-B:     {DinoPizza}  ← посещал, но не заказывал
-- 
-- ПОЧЕМУ EXCEPT, А НЕ ДРУГИЕ ОПЕРАТОРЫ:
-- - LEFT JOIN + IS NULL: сложнее, больше кода
-- - NOT IN: проблемы с NULL значениями
-- - NOT EXISTS: коррелированный подзапрос (сложнее)
-- - EXCEPT: простой, читаемый, декларативный

-- ============================================================================
-- ЧАСТЬ 2: Все пиццерии, откуда Андрей делал заказы
-- ============================================================================

SELECT pizz.name
-- ↑↑↑
-- КОММЕНТАРИЙ: Выбираем название пиццерии (без алиаса, но тип совместим)
-- - Тип данных: VARCHAR (совместим с первым SELECT)
-- - Количество колонок: 1 (совпадает с первым SELECT)

FROM person_order ord
-- ↑↑↑
-- КОММЕНТАРИЙ: Таблица заказов (журнал заказов клиентов)
-- - ord: алиас для person_order
-- - Содержит: person_id, menu_id, order_date
-- - Это ОСНОВНАЯ таблица для второго запроса (заказы)
-- 
-- ПРИМЕР ДАННЫХ:
-- ┌─────┬───────────┬─────────────────────┐
-- │ id  │ person_id │ menu_id │ order_date │
-- ├─────┼───────────┼─────────┼────────────┤
-- │ 3   │ 2 (Andrey)│ 8       │ 2022-01-03 │
-- │ 4   │ 2 (Andrey)│ 9       │ 2022-01-04 │
-- └────────────────┴─────────┴────────────┘

INNER JOIN person client 
    ON client.id = ord.person_id
-- ↑↑↑
-- КОММЕНТАРИЙ: Присоединяем таблицу person для фильтрации по имени
-- - client.id = ord.person_id: связываем заказ с конкретным человеком
-- - INNER JOIN: берём только существующих клиентов
-- 
-- ПОТОК ДАННЫХ:
--   person_order (person_id=2)
--   ↓ JOIN
--   person (id=2, name='Andrey', gender='male')
--   ↓
--   Результат: заказы только для Andrey

INNER JOIN menu 
    ON menu.id = ord.menu_id
-- ↑↑↑
-- КОММЕНТАРИЙ: Присоединяем таблицу menu для получения pizzeria_id
-- - ord.menu_id = menu.id: связываем заказ с конкретной пиццей
-- - Нужно для получения pizzeria_id (меню привязано к пиццерии)
-- 
-- ПОТОК ДАННЫХ:
--   person_order (menu_id=8)
--   ↓ JOIN
--   menu (id=8, pizzeria_id=3, pizza_name='mushroom pizza')
--   ↓
--   Результат: пицца из пиццерии id=3 (DoDo Pizza)
-- 
-- ВАЖНО: person_order не содержит pizzeria_id напрямую!
-- Нужно идти через menu: person_order → menu → pizzeria

INNER JOIN pizzeria pizz 
    ON pizz.id = menu.pizzeria_id
-- ↑↑↑
-- КОММЕНТАРИЙ: Присоединяем таблицу pizzeria для получения названия
-- - menu.pizzeria_id = pizz.id: связываем меню с пиццерией
-- - Получаем название пиццерии вместо ID
-- 
-- ПОТОК ДАННЫХ:
--   menu (pizzeria_id=3)
--   ↓ JOIN
--   pizzeria (id=3, name='DoDo Pizza')
--   ↓
--   Результат: 'DoDo Pizza'

WHERE client.name = 'Andrey'
-- ↑↑↑
-- КОММЕНТАРИЙ: Фильтруем только заказы Андрея
-- - name = 'Andrey': оставляем только этого клиента
-- - Все заказы других людей исключаются
-- 
-- ПРИМЕР ДАННЫХ ПОСЛЕ ФИЛЬТРА:
-- ┌─────────────────┐
-- │ pizzeria_name   │
-- ├─────────────────┤
-- │ DoDo Pizza      │  ← Андрей заказал 03.01.2022
-- │ Papa Johns      │  ← Андрей заказал 04.01.2022
