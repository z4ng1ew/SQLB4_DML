INSERT INTO person_order (id, person_id, menu_id, order_date)
SELECT 
    (SELECT MAX(id) FROM person_order) + gs,  -- Уникальный ID: MAX+1, MAX+2, ...
    p.id,                                      -- ID человека
    (SELECT id FROM menu WHERE pizza_name = 'greek pizza' LIMIT 1),  -- ID пиццы
    '2022-02-25'                               -- Дата заказа
FROM person p
CROSS JOIN generate_series(1, (SELECT COUNT(*) FROM person)) AS gs
--         ────────────────┬────────────────────────────
