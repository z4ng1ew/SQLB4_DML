## 🎓 Комментарий для УСТНОЙ защиты

```markdown
## Объяснение скрипта для защиты

**Задача:**
Создать заказы на greek pizza для ВСЕХ людей в базе (9 человек) на 25.02.2022.

**Отличие от заданий 09-10:**
- Задания 09-10: Два отдельных INSERT для Denis и Irina
- Задание 12: ОДИН INSERT для ВСЕХ людей (массовая вставка)

**Структура скрипта (3 шага):**

### **Шаг 1: DELETE (идемпотентность)**
Стандартная очистка старых заказов перед вставкой новых.

### **Шаг 2: INSERT с SELECT (ключевая секция)**
```sql
INSERT INTO person_order (id, person_id, menu_id, order_date)
SELECT 
    (SELECT MAX(id) FROM person_order) + gs,
    p.id,
    (SELECT id FROM menu WHERE pizza_name = 'greek pizza' LIMIT 1),
    '2022-02-25'
FROM person p
CROSS JOIN generate_series(1, (SELECT COUNT(*) FROM person)) AS gs
WHERE gs = p.id;
```

**Разберём по частям:**

#### **1. generate_series**
```sql
generate_series(1, (SELECT COUNT(*) FROM person))
```

**Что делает:**
Генерирует последовательность чисел от 1 до количества людей.

**Пример:**
```
COUNT(*) FROM person = 9
generate_series(1, 9) = {1, 2, 3, 4, 5, 6, 7, 8, 9}
```

Создаётся виртуальная таблица:
```
┌────┐
│ gs │
├────┤
│ 1  │
│ 2  │
│ ...│
│ 9  │
└────┘
```

#### **2. CROSS JOIN**
```sql
FROM person p
CROSS JOIN generate_series(...) AS gs
```

**Что делает:**
Создаёт декартово произведение — каждый человек соединяется с каждым числом.

**Результат:**
```
9 человек × 9 чисел = 81 комбинация

(Anna, 1), (Anna, 2), (Anna, 3), ..., (Anna, 9)
(Andrey, 1), (Andrey, 2), ..., (Andrey, 9)
...
(Dmitriy, 1), (Dmitriy, 2), ..., (Dmitriy, 9)
```

#### **3. WHERE gs = p.id (критическая фильтрация!)**
```sql
WHERE gs = p.id
```

**Что делает:**
Из 81 комбинации оставляет только те, где номер совпадает с ID человека.

**Результат после фильтрации:**
```
(Anna [id=1], 1)     ← Совпало! ✅
(Andrey [id=2], 2)   ← Совпало! ✅
(Kate [id=3], 3)     ← Совпало! ✅
...
(Dmitriy [id=9], 9)  ← Совпало! ✅

Всего: 9 строк (вместо 81)
```

**Зачем это нужно:**
- Без WHERE получили бы 81 заказ (каждый человек заказал 9 раз!)
- С WHERE получаем 9 заказов (каждый человек ровно 1 раз)

#### **4. Вычисление ID заказа**
```sql
(SELECT MAX(id) FROM person_order) + gs
```

**Логика:**
```
MAX(id) в person_order = 22 (допустим)

Anna (gs=1):    id = 22 + 1 = 23
Andrey (gs=2):  id = 22 + 2 = 24
Kate (gs=3):    id = 22 + 3 = 25
...
Dmitriy (gs=9): id = 22 + 9 = 31
```

**Важно:**
Подзапрос MAX(id) выполняется ОДИН РАЗ, не для каждой строки!
Поэтому все ID последовательные и уникальные.

### **Финальный результат:**
```
┌────┬───────────┬─────────┬────────────┐
│ id │ person_id │ menu_id │ order_date │
├────┼───────────┼─────────┼────────────┤
│ 23 │ 1 (Anna)  │ 19      │ 2022-02-25 │
│ 24 │ 2 (Andrey)│ 19      │ 2022-02-25 │
│ 25 │ 3 (Kate)  │ 19      │ 2022-02-25 │
│ ...│ ...       │ ...     │ ...        │
│ 31 │ 9 (Dmitr) │ 19      │ 2022-02-25 │
└────┴───────────┴─────────┴────────────┘

9 заказов, все на greek pizza (menu_id=19)
```

### **Шаг 3: SELECT (проверка)**
Проверяем, что создано ровно 9 заказов.

### **Важные моменты:**

**1. Зачем такая сложная конструкция?**

Преимущества:
- Один запрос вместо 9
- Автоматическая адаптация к количеству людей
- Быстрее (одна транзакция)
- Масштабируемо (100 человек? Код не меняется!)

**2. Альтернатива:**
Можно было сделать 9 отдельных INSERT (как в заданиях 09-10).
Но это громоздко и не масштабируемо.

**3. Граничный случай:**
Если в person.id есть пропуски (например, 1,2,5,7,9),
то WHERE gs = p.id создаст только 5 заказов (не 9).

В нашей базе ID последовательные: {1,2,3,4,5,6,7,8,9} ✅

**4. Производительность:**
INSERT + SELECT выполняется как одна атомарная операция — быстрее и надёжнее.
