-- ============================================================================
--                          ДЕНЬ 03 | ЗАДАНИЕ 03
--              Анализ гендерного дисбаланса посещений пиццерий
-- ============================================================================

/*
 * КОНЦЕПЦИЯ ЗАПРОСА:
 * Этот запрос использует операторы теории множеств с сохранением кратности
 * (multiset operations) для анализа разницы в паттернах посещений.
 * 
 * ТЕОРИЯ МНОЖЕСТВ VS МУЛЬТИМНОЖЕСТВ:
 * - Множество: {a, b, c} — элементы уникальны
 * - Мультимножество: {a, a, a, b, c} — элементы могут повторяться
 * 
 * SQL с ALL работает с мультимножествами!
 */

-- ============================================================================
-- БЛОК A: Женские предпочтения (female > male)
-- ============================================================================

(
    /*
     * ПОДЗАПРОС A1: Все женские посещения
     * Каждое посещение = одна запись в результате
     */
    SELECT pizz.name AS pizzeria_name
    FROM person client
        -- JOIN 1: Связываем клиента с посещениями
        INNER JOIN person_visits visit 
            ON client.id = visit.person_id
        -- JOIN 2: Связываем посещения с пиццериями
        INNER JOIN pizzeria pizz 
            ON pizz.id = visit.pizzeria_id
    WHERE client.gender = 'female'
    
    /*
     * ПРИМЕР РЕЗУЛЬТАТА ПОДЗАПРОСА A1:
     * ┌───────────────┐
     * │ pizzeria_name │
     * ├───────────────┤
     * │ DinoPizza     │  ← Anna посетила 2022-01-04
     * │ DinoPizza     │  ← Kate посетила 2022-01-04
     * │ DinoPizza     │  ← Elvira посетила 2022-01-09
     * │ Best Pizza    │  ← Kate посетила 2022-01-03
     * │ Dominos       │  ← Elvira посетила 2022-01-08
     * │ Dominos       │  ← Irina посетила 2022-01-09
     * │ ...           │
     * └───────────────┘
     * 
     * Важно: DinoPizza появляется 3 раза (3 женщины посетили)
     */
    
    -- ========================================================================
    -- ОПЕРАТОР EXCEPT ALL
    -- ========================================================================
    
    EXCEPT ALL
    
    /*
     * ПОДЗАПРОС A2: Все мужские посещения
     */
    SELECT pizz.name
    FROM person client
        INNER JOIN person_visits visit 
            ON client.id = visit.person_id
        INNER JOIN pizzeria pizz 
            ON pizz.id = visit.pizzeria_id
    WHERE client.gender = 'male'
    
    /*
     * ПРИМЕР РЕЗУЛЬТАТА ПОДЗАПРОСА A2:
     * ┌───────────────┐
     * │ pizzeria_name │
     * ├───────────────┤
     * │ DinoPizza     │  ← Denis посетил 2022-01-08
     * │ Best Pizza    │  ← Denis посетил 2022-01-07
     * │ Best Pizza    │  ← Dmitriy посетил 2022-01-09
     * │ Dominos       │  ← Andrey посетил 2022-01-01
     * │ Dominos       │  ← Peter посетил 2022-01-05
     * │ ...           │
     * └───────────────┘
     * 
     * Важно: DinoPizza появляется 1 раз, Best Pizza — 2 раза
     */
    
    /*
     * РАБОТА EXCEPT ALL (вычитание мультимножеств):
     * 
     * Алгоритм:
     * 1. Для каждого уникального значения подсчитываем количество в A1 и A2
     * 2. Если count(A1) > count(A2), оставляем count(A1) - count(A2) копий
     * 3. Если count(A1) <= count(A2), не оставляем ничего
     * 
     * Пример расчёта:
     * 
     * DinoPizza:
     *   В A1 (female): 3 записи
     *   В A2 (male):   1 запись
     *   Результат: 3 - 1 = 2 записи {DinoPizza, DinoPizza}
     * 
     * Best Pizza:
     *   В A1 (female): 1 запись
     *   В A2 (male):   2 записи
     *   Результат: 1 - 2 = -1 → ничего (отрицательное)
     * 
     * Dominos:
     *   В A1 (female): 2 записи
     *   В A2 (male):   2 записи
     *   Результат: 2 - 2 = 0 → ничего (равенство)
     * 
     * РЕЗУЛЬТАТ БЛОКА A:
     * ┌───────────────┐
     * │ pizzeria_name │
     * ├───────────────┤
     * │ DinoPizza     │  ← первая копия
     * │ DinoPizza     │  ← вторая копия
     * └───────────────┘
     */
)

-- ============================================================================
-- ОПЕРАТОР UNION ALL
-- ============================================================================

UNION ALL

/*
 * UNION ALL объединяет мультимножества БЕЗ удаления дубликатов
 * 
 * Если:
 * Блок A = {DinoPizza, DinoPizza}
 * Блок B = {Best Pizza, Dominos}
 * 
 * То UNION ALL = {DinoPizza, DinoPizza, Best Pizza, Dominos}
 * 
 * Сравнение с UNION (без ALL):
 * UNION = {Best Pizza, DinoPizza, Dominos}  ← убрал дубликаты!
 */

-- ============================================================================
-- БЛОК B: Мужские предпочтения (male > female)
-- ============================================================================
-- Структура зеркальна Блоку A (меняем местами гендеры)

(
    /*
     * ПОДЗАПРОС B1: Все мужские посещения
