# 🏷️ Алиас таблицы (Table Alias)

## 🎯 Что это такое?

```sql
FROM person client
     ──────┬──────
           │
           └──> Это АЛИАС (псевдоним) таблицы
```

**`client`** = **короткое имя** для таблицы `person`

Вместо того чтобы каждый раз писать `person.name`, `person.id`, можно написать `client.name`, `client.id`

---

## 📚 Два способа создания алиаса

### **Способ 1: Без AS (короткая форма)**

```sql
FROM person client
```

### **Способ 2: С AS (явная форма)**

```sql
FROM person AS client
```

**Оба варианта абсолютно одинаковы!** Обычно используют первый (короче).

---

## 🍕 Пример из твоего запроса

### **Без алиаса (длинно и неудобно):**

```sql
SELECT person.name, pizzeria.name
FROM person
INNER JOIN person_visits ON person.id = person_visits.person_id
INNER JOIN pizzeria ON pizzeria.id = person_visits.pizzeria_id
WHERE person.gender = 'female';
      ──────────────
        ↑
    Каждый раз пишем полное имя таблицы
```

### **С алиасом (коротко и понятно):**

```sql
SELECT client.name, pizz.name
FROM person client
     ──────┬──────
           │
       Даём короткое имя: "client"
       
INNER JOIN person_visits visit ON client.id = visit.person_id
                         ─────     ──────
                           ↑          ↑
                    Алиас для     Используем
                  person_visits    алиас "client"
                  
INNER JOIN pizzeria pizz ON pizz.id = visit.pizzeria_id
                    ────     ────
                      ↑        ↑
                   Алиас   Используем алиас
                   
WHERE client.gender = 'female';
      ──────
        ↑
    Используем алиас вместо "person"
```

---

## 💡 Зачем нужны алиасы?

### **1. Короче писать**

```sql
-- ❌ Без алиаса (длинно)
SELECT person.name, person.age, person.address
FROM person
WHERE person.gender = 'female';

-- ✅ С алиасом (коротко)
SELECT p.name, p.age, p.address
FROM person p
WHERE p.gender = 'female';
```

### **2. Обязательны при самосоединении (SELF JOIN)**

Когда нужно соединить таблицу саму с собой:

```sql
-- Найти пары людей одного возраста
SELECT p1.name AS person1, 
       p2.name AS person2
FROM person p1
     ──────┬──
           │
        Первый экземпляр таблицы person
        
INNER JOIN person p2 ON p1.age = p2.age
           ──────┬──
                 │
            Второй экземпляр той же таблицы!
            
WHERE p1.id < p2.id;  -- Чтобы не было дубликатов
```

**Без алиасов это невозможно!**

### **3. Делают код читаемым**

```sql
-- ❌ Непонятно
SELECT p.name, pz.name
FROM person p
JOIN pizzeria pz;

-- ✅ Понятно из контекста
SELECT client.name, restaurant.name
FROM person client
JOIN pizzeria restaurant;
```

