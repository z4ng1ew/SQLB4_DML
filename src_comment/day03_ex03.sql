-- ============================================================================
-- СРАВНЕНИЕ: EXCEPT vs EXCEPT ALL
-- ============================================================================

/*
┌──────────────┬─────────────────────────┬─────────────────────────┐
│              │  EXCEPT                 │  EXCEPT ALL             │
├──────────────┼─────────────────────────┼─────────────────────────┤
│ Обработка    │ Сначала DISTINCT,       │ Вычитает поэлементно    │
│              │ потом вычитание         │ (учитывает количество)  │
├──────────────┼─────────────────────────┼─────────────────────────┤
│ Пример       │ A={a,a,a,b}             │ A={a,a,a,b}             │
│              │ B={a,b}                 │ B={a,b}                 │
│              │ A-B = {}                │ A-B = {a,a}             │
│              │ (после DISTINCT: A'={a,b})│ (3-1=2 копии 'a')     │
├──────────────┼─────────────────────────┼─────────────────────────┤
│ Использование│ Уникальные различия     │ Количественные различия │
│              │ между множествами       │ между мультимножествами │
└──────────────┴─────────────────────────┴─────────────────────────┘
*/

-- ============================================================================
-- СРАВНЕНИЕ: UNION vs UNION ALL
-- ============================================================================

/*
┌──────────────┬─────────────────────────┬─────────────────────────┐
│              │  UNION                  │  UNION ALL              │
├──────────────┼─────────────────────────┼─────────────────────────┤
│ Дубликаты    │ Удаляются (DISTINCT)    │ Сохраняются             │
├──────────────┼─────────────────────────┼─────────────────────────┤
│ Пример       │ A={a,a,b}               │ A={a,a,b}               │
│              │ B={a,c}                 │ B={a,c}                 │
│              │ A∪B = {a,b,c}           │ A∪B = {a,a,a,b,c}       │
├──────────────┼─────────────────────────┼─────────────────────────┤
│ Производ-    │ Медленнее (нужен        │ Быстрее (без сортировки │
│ ительность   │ DISTINCT/сортировка)    │ и дедупликации)         │
└──────────────┴─────────────────────────┴─────────────────────────┘
*/
```

