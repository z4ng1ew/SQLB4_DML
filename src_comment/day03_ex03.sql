```markdown
## Объяснение запроса для защиты

**Задача:**
Найти пиццерии, которые посещали чаще женщины или чаще мужчины, 
с сохранением информации о разнице в количестве посещений.

**Ключевое требование:**
Использовать операторы множеств с ALL (EXCEPT ALL, UNION ALL), 
которые сохраняют дубликаты.

**Структура запроса:**

Запрос состоит из двух симметричных блоков, объединённых UNION ALL:

**Блок A (женщины чаще):**
1. Берём ВСЕ посещения пиццерий женщинами (с дубликатами)
2. EXCEPT ALL вычитаем ВСЕ посещения мужчинами
3. Остаются пиццерии, где женщин было больше

**Блок B (мужчины чаще):**
1. Берём ВСЕ посещения пиццерий мужчинами (с дубликатами)
2. EXCEPT ALL вычитаем ВСЕ посещения женщинами
3. Остаются пиццерии, где мужчин было больше

**UNION ALL** объединяет оба результата, сохраняя дубликаты.

**Почему EXCEPT ALL, а не EXCEPT?**

EXCEPT ALL учитывает количество повторений:
- Если DinoPizza посещали 5 раз женщины и 2 раза мужчины
- EXCEPT ALL даст: 5 - 2 = 3 записи "DinoPizza"
- Обычный EXCEPT дал бы: 1 запись "DinoPizza" (без учёта количества)

Дубликаты в результате показывают "силу дисбаланса" — 
сколько раз одна группа посещала пиццерию больше другой.

**Почему нужны скобки?**

EXCEPT имеет более высокий приоритет, чем UNION ALL. 
Без скобок операции выполнятся в неправильном порядке.

**Каждый подзапрос использует цепочку JOIN:**
person → person_visits → pizzeria
для получения названий пиццерий, которые посещал конкретный гендер.

**Симметрия блоков:**
Блоки A и B зеркальны — просто меняются местами 'female' и 'male'.
Это гарантирует, что мы найдём дисбаланс в любую сторону.
