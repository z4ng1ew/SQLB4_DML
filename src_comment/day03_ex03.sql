## ⚠️ Важные правила

### **1. После создания алиаса НЕЛЬЗЯ использовать оригинальное имя**

```sql
-- ❌ ОШИБКА
FROM person client
WHERE person.gender = 'female';  -- person уже недоступна!
      ──────
        ↑
    Ошибка! Нужно использовать "client"

-- ✅ ПРАВИЛЬНО
FROM person client
WHERE client.gender = 'female';
```

### **2. Алиас действует только в пределах запроса**

```sql
-- Запрос 1
SELECT * FROM person p WHERE p.age > 18;

-- Запрос 2 (алиас "p" из запроса 1 недоступен)
SELECT * FROM person client WHERE client.age < 18;
```

### **3. Алиас можно использовать сразу после FROM**

```sql
SELECT client.name      -- ✅ Можно использовать
FROM person client      -- Создали здесь
WHERE client.age > 18;  -- ✅ И здесь тоже
```

