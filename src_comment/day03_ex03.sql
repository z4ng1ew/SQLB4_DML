## ⚠️ Частые ошибки

```sql
-- ❌ ОШИБКА 1: Забыли скобки
SELECT * FROM a EXCEPT ALL SELECT * FROM b
UNION ALL
SELECT * FROM c EXCEPT ALL SELECT * FROM d;

-- Может интерпретироваться неправильно из-за приоритета операций!

-- ✅ ПРАВИЛЬНО: Явные скобки
(SELECT * FROM a EXCEPT ALL SELECT * FROM b)
UNION ALL
(SELECT * FROM c EXCEPT ALL SELECT * FROM d);

-- ❌ ОШИБКА 2: Использовали EXCEPT вместо EXCEPT ALL
EXCEPT  -- Потеряет информацию о количестве!

-- ✅ ПРАВИЛЬНО
EXCEPT ALL  -- Сохраняет дубликаты

-- ❌ ОШИБКА 3: Разные имена колонок в блоках
SELECT pizz.name AS pizzeria_name FROM ...
UNION ALL
SELECT pizz.name AS restaurant_name FROM ...  -- Разные алиасы!

-- ✅ ПРАВИЛЬНО: Одинаковые имена
SELECT pizz.name AS pizzeria_name FROM ...
UNION ALL
SELECT pizz.name AS pizzeria_name FROM ...
```

---

## 🎯 Ключевые моменты для защиты

1. **EXCEPT ALL сохраняет дубликаты** — вычитает с учётом количества
2. **UNION ALL объединяет без удаления** — сохраняет все повторения
3. **Блоки симметричны** — меняются местами только гендеры
4. **Дубликаты имеют смысл** — показывают "силу дисбаланса"
5. **Скобки обязательны** — для правильного порядка операций

