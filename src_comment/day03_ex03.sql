    -- ========================================================================
    
    EXCEPT ALL
    
    -- ========================================================================
    
    /*
     * ПОДЗАПРОС B2: Все женские посещения
     */
    SELECT pizz.name
    FROM person client
        INNER JOIN person_visits visit 
            ON client.id = visit.person_id
        INNER JOIN pizzeria pizz 
            ON pizz.id = visit.pizzeria_id
    WHERE client.gender = 'female'
    
    /*
     * ПРИМЕР РАСЧЁТА ДЛЯ БЛОКА B:
     * 
     * Best Pizza:
     *   В B1 (male):   2 записи
     *   В B2 (female): 1 запись
     *   Результат: 2 - 1 = 1 запись {Best Pizza}
     * 
     * DinoPizza:
     *   В B1 (male):   1 запись
     *   В B2 (female): 3 записи
     *   Результат: 1 - 3 = -2 → ничего
     * 
     * РЕЗУЛЬТАТ БЛОКА B:
     * ┌───────────────┐
     * │ pizzeria_name │
     * ├───────────────┤
     * │ Best Pizza    │
     * └───────────────┘
     */
)

-- ============================================================================
-- ФИНАЛЬНАЯ СОРТИРОВКА
-- ============================================================================

ORDER BY 1;  -- ORDER BY pizzeria_name

/*
 * ФИНАЛЬНЫЙ РЕЗУЛЬТАТ (после UNION ALL и ORDER BY):
 * 
 * Блок A: {DinoPizza, DinoPizza}
 * Блок B: {Best Pizza}
 * 
 * UNION ALL: {DinoPizza, DinoPizza, Best Pizza}
 * 
 * После ORDER BY 1:
 * ┌───────────────┐
 * │ pizzeria_name │
 * ├───────────────┤
 * │ Best Pizza    │  ← Мужчины на 1 посещение больше
 * │ DinoPizza     │  ← Женщины на 2 посещения больше (копия 1)
 * │ DinoPizza     │  ← Женщины на 2 посещения больше (копия 2)
 * └───────────────┘
 * 
 * ИНТЕРПРЕТАЦИЯ:
 * - Best Pizza: мужчины доминируют (1 лишнее посещение)
 * - DinoPizza: женщины доминируют (2 лишних посещения, поэтому 2 строки)
 */

-- ============================================================================
-- СРАВНЕНИЕ: EXCEPT vs EXCEPT ALL
-- ============================================================================

/*
 * Если бы использовали EXCEPT вместо EXCEPT ALL:
 * 
 * Блок A:
 *   A1 (female): {DinoPizza, DinoPizza, DinoPizza, Best Pizza, ...}
 *   A2 (male):   {DinoPizza, Best Pizza, Best Pizza, ...}
 *   
 *   Сначала DISTINCT:
 *   A1': {DinoPizza, Best Pizza, ...}
 *   A2': {DinoPizza, Best Pizza, ...}
 *   
 *   EXCEPT: A1' - A2' = {} (может быть пусто!)
 * 
 * С EXCEPT ALL информация о количестве посещений сохраняется!
 */

-- ============================================================================
-- ПОЧЕМУ НУЖНЫ СКОБКИ ВОКРУГ БЛОКОВ:
-- ============================================================================

/*
 * Приоритет операций (от высокого к низкому):
 * 1. INTERSECT
 * 2. EXCEPT
 * 3. UNION
 * 
 * Без скобок запрос интерпретируется так:
 * 
 * A EXCEPT ALL B UNION ALL C EXCEPT ALL D
 * = (A EXCEPT ALL B) UNION ALL (C EXCEPT ALL D)  ← правильно!
 * 
 * Но для ясности и избежания ошибок лучше явно указать скобки.
 * Это делает код самодокументированным.
 */

-- ============================================================================
