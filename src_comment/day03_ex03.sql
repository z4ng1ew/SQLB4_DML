## 🎓 Для защиты проекта

**Вопрос:** Что означает `FROM person client`?

**Твой ответ:**

> "`client`" — это алиас (псевдоним) для таблицы `person`. Это короткое имя, которое я даю таблице, чтобы не писать каждый раз полное название. Вместо `person.gender` я могу написать `client.gender` — это короче и понятнее по смыслу, ведь в контексте задачи `person` — это клиент пиццерии. Алиасы особенно полезны при JOIN'ах, когда одна таблица используется несколько раз или когда нужно сделать код более читаемым."

