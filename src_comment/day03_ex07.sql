**Зачем:**
Делает скрипт идемпотентным — его можно запускать многократно без ошибок.

**Что происходит:**
- При первом запуске: удалит 0 строк (записи с id=19 нет)
- При втором запуске: удалит 1 строку (освободит id=19 для новой вставки)

**Без DELETE:**
Повторный запуск вызовет ошибку: "duplicate key value violates unique constraint"

### **Шаг 2: INSERT**
```sql
INSERT INTO menu(id, pizzeria_id, pizza_name, price) 
VALUES (19, 2, 'greek pizza', 800);
```

**Значения:**
- `id = 19`: Следующий свободный ID (максимальный в базе = 18)
- `pizzeria_id = 2`: ID ресторана Dominos (проверяется внешним ключом)
- `pizza_name = 'greek pizza'`: Название по заданию
- `price = 800`: Цена по заданию

**Проверки PostgreSQL:**
- PRIMARY KEY: id=19 должен быть уникален
- FOREIGN KEY: pizzeria_id=2 должен существовать в таблице pizzeria

### **Шаг 3: SELECT (проверка)**
```sql
SELECT count(*) = 1 AS is_inserted
FROM menu
WHERE id = 19 AND pizzeria_id = 2 
