## 💡 Зачем это нужно?

### **Без FOREIGN KEY:**

```sql
-- Можно было бы вставить:
INSERT INTO menu VALUES (19, 999, 'greek pizza', 800);
                             ↑
                    Несуществующая пиццерия!

-- А потом при запросе:
SELECT m.pizza_name, p.name
FROM menu m
JOIN pizzeria p ON m.pizzeria_id = p.id
WHERE m.id = 19;

-- Результат:
(пусто)  ← Пицца есть, но пиццерии нет! 😱
```

**Проблемы:**
- ❌ Битые ссылки (orphan records)
- ❌ Невозможно найти, где эта пицца продаётся
- ❌ База данных в неконсистентном состоянии

---

### **С FOREIGN KEY:**

```sql
-- Попытка вставить несуществующую пиццерию:
INSERT INTO menu VALUES (19, 999, 'greek pizza', 800);

-- ❌ ERROR сразу!
-- PostgreSQL не позволит создать битую ссылку!
```

**Преимущества:**
- ✅ Целостность данных гарантирована
- ✅ Все ссылки всегда корректны
- ✅ Нет "потерянных" записей

