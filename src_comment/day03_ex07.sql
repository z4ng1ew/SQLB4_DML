## 🔍 Как это работает в базе данных

### **При создании таблицы `menu` было указано:**

```sql
CREATE TABLE menu (
    id bigint primary key,
    pizzeria_id bigint not null,
    pizza_name varchar not null,
    price numeric not null,
    
    -- ВОТ ОНО! Правило связи:
    CONSTRAINT fk_menu_pizzeria_id 
        FOREIGN KEY (pizzeria_id) 
        REFERENCES pizzeria(id)
);
```

**Что это значит:**

```
FOREIGN KEY (pizzeria_id)     ← Столбец в таблице menu
REFERENCES pizzeria(id)       ← Ссылается на столбец id в таблице pizzeria
```

**На русском языке:**

> "Поле `pizzeria_id` в таблице `menu` ДОЛЖНО ссылаться на СУЩЕСТВУЮЩИЙ `id` в таблице `pizzeria`"

