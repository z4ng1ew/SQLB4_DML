## Объяснение скрипта для защиты

**Задача:**
Добавить новую пиццу "greek pizza" по цене 800 рублей в ресторан Dominos.

**Структура скрипта (3 шага):**

### **Шаг 1: DELETE**
```sql
DELETE FROM menu WHERE id = 19;
