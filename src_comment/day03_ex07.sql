## 📋 Пошаговая проверка PostgreSQL

### **Каждый раз при INSERT или UPDATE:**

```
Шаг 1: Ты делаешь INSERT
INSERT INTO menu VALUES (19, 2, 'greek pizza', 800);
                             ↑
                        pizzeria_id = 2

Шаг 2: PostgreSQL проверяет FOREIGN KEY
"Есть ли в таблице pizzeria строка с id = 2?"

Шаг 3: PostgreSQL ищет в pizzeria
SELECT id FROM pizzeria WHERE id = 2;

Шаг 4a: Если НАШЁЛ
→ ✅ INSERT разрешён

Шаг 4b: Если НЕ НАШЁЛ
→ ❌ ERROR: foreign key constraint violation
```

