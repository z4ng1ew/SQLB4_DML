# 🔗 FOREIGN KEY — объясняю просто

## 🎯 Что это такое?

**FOREIGN KEY (внешний ключ)** = **правило связи между таблицами**

PostgreSQL следит, чтобы связи были **правильными** (не ссылались на несуществующие данные).

