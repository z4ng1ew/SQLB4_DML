**Как работает:**
- `count(*)` подсчитывает строки, соответствующие условиям
- `count(*) = 1` возвращает TRUE, если найдена ровно 1 запись
- Результат `t` (TRUE) означает успешную вставку

**Ожидаемый результат:**
```
is_inserted
-----------
t
```

**Если FALSE:**
