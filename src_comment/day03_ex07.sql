```sql
-- ============================================================================
--                          ДЕНЬ 03 | ЗАДАНИЕ 07
--                  Добавление новой пиццы: Greek Pizza
-- ============================================================================

/*
 * КОНТЕКСТ ЗАДАНИЯ:
 * В ресторанной сети появилась новая пицца - "greek pizza".
 * Её нужно добавить в меню ресторана Dominos по цене 800₽.
