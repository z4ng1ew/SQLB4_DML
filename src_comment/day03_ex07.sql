**Вопрос:** Что такое FOREIGN KEY constraint?

**Твой ответ:**

> "FOREIGN KEY (внешний ключ) — это правило, которое гарантирует корректность связей между таблицами. В моём примере `menu.pizzeria_id` ссылается на `pizzeria.id` через FOREIGN KEY constraint.
>
> Это значит, что PostgreSQL автоматически проверяет: если я вставляю пиццу с `pizzeria_id = 2`, то пиццерия с `id = 2` ДОЛЖНА существовать в таблице `pizzeria`.
>
> Если я попытаюсь вставить `pizzeria_id = 999`, а такой пиццерии нет, PostgreSQL выдаст ошибку и не позволит создать битую ссылку. Это защищает целостность данных — все ссылки всегда корректны."

