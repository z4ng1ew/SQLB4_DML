 */

-- ============================================================================
-- ШАГ 1: ПОДГОТОВКА (Обеспечение идемпотентности)
-- ============================================================================

DELETE FROM menu WHERE id = 19;

/*
 * ИДЕМПОТЕНТНОСТЬ - это свойство операции давать одинаковый результат
 * при многократном выполнении.
 * 
 * БЕЗ DELETE:
 * ┌──────────────┬─────────────────────────────────────┐
 * │ Запуск       │ Результат                           │
 * ├──────────────┼─────────────────────────────────────┤
 * │ 1-й раз      │ ✅ INSERT успешно                   │
 * │ 2-й раз      │ ❌ ERROR: duplicate key id=19       │
 * │ 3-й раз      │ ❌ ERROR: duplicate key id=19       │
 * └──────────────┴─────────────────────────────────────┘
 * 
 * С DELETE:
 * ┌──────────────┬─────────────────────────────────────┐
 * │ Запуск       │ Результат                           │
 * ├──────────────┼─────────────────────────────────────┤
 * │ 1-й раз      │ DELETE 0 строк → INSERT успешно ✅  │
 * │ 2-й раз      │ DELETE 1 строку → INSERT успешно ✅ │
 * │ 3-й раз      │ DELETE 1 строку → INSERT успешно ✅ │
 * └──────────────┴─────────────────────────────────────┘
 * 
 * Каждый запуск даёт одинаковый результат!
 */

-- ============================================================================
-- ШАГ 2: ВСТАВКА ДАННЫХ
-- ============================================================================

INSERT INTO menu(id, pizzeria_id, pizza_name, price) 
VALUES (19, 2, 'greek pizza', 800);

/*
 * ДЕТАЛЬНЫЙ РАЗБОР ВСТАВЛЯЕМЫХ ЗНАЧЕНИЙ:
 * 
 * ┌──────────────┬────────┬─────────────────────────────────┐
 * │ Поле         │ Значен.│ Обоснование                     │
 * ├──────────────┼────────┼─────────────────────────────────┤
 * │ id           │ 19     │ Следующий после max(id)=18      │
 * │              │        │ Требование: прямое числовое     │
 * │              │        │ значение (не подзапрос)         │
 * ├──────────────┼────────┼─────────────────────────────────┤
 * │ pizzeria_id  │ 2      │ ID ресторана Dominos            │
 * │              │        │ Проверяется FK constraint       │
 * │              │        │ Требование: прямое числовое     │
 * ├──────────────┼────────┼─────────────────────────────────┤
 * │ pizza_name   │ greek  │ Название из условия задания     │
 * │              │ pizza  │                                 │
 * ├──────────────┼────────┼─────────────────────────────────┤
 * │ price        │ 800    │ Цена из условия задания         │
 * └──────────────┴────────┴─────────────────────────────────┘
 * 
 * АВТОМАТИЧЕСКИЕ ПРОВЕРКИ PostgreSQL:
 * 
 * 1. PRIMARY KEY constraint (menu_pkey):
 *    ✅ id=19 уникален (после DELETE освобождён)
 * 
 * 2. FOREIGN KEY constraint (fk_menu_pizzeria_id):
 *    ✅ pizzeria_id=2 существует в pizzeria(id)
 *    
 *    Проверка:
 *    SELECT id, name FROM pizzeria WHERE id = 2;
 *    → (2, 'Dominos')  ← Существует!
 * 
 * 3. NOT NULL constraints:
 *    ✅ Все обязательные поля заполнены
 * 
 * 4. CHECK constraints:
 *    ✅ price >= 1 (default constraint на price)
 */

/*
 * ВИЗУАЛИЗАЦИЯ ИЗМЕНЕНИЯ:
 * 
 * ДО INSERT (последние 3 строки menu):
 * ┌────┬─────────────┬───────────────┬───────┐
 * │ id │ pizzeria_id │ pizza_name    │ price │
 * ├────┼─────────────┼───────────────┼───────┤
 * │ 16 │ 5           │ cheese pizza  │ 700   │
 * │ 17 │ 5           │ pepperoni     │ 800   │
 * │ 18 │ 5           │ supreme pizza │ 850   │
 * └────┴─────────────┴───────────────┴───────┘
 * 
 * ПОСЛЕ INSERT:
 * ┌────┬─────────────┬───────────────┬───────┐
 * │ id │ pizzeria_id │ pizza_name    │ price │
 * ├────┼─────────────┼───────────────┼───────┤
 * │ 16 │ 5           │ cheese pizza  │ 700   │
 * │ 17 │ 5           │ pepperoni     │ 800   │
 * │ 18 │ 5           │ supreme pizza │ 850   │
 * │ 19 │ 2           │ greek pizza   │ 800   │ ← НОВАЯ!
 * └────┴─────────────┴───────────────┴───────┘
 *              ↑
 *         Dominos (id=2)
 */

-- ============================================================================
-- ШАГ 3: ВЕРИФИКАЦИЯ (Проверка корректности)
-- ============================================================================

SELECT count(*) = 1 AS is_inserted
FROM menu
WHERE id = 19
  AND pizzeria_id = 2
  AND pizza_name = 'greek pizza'
  AND price = 800;

/*
