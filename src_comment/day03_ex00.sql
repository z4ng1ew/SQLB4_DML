-- Задание: Найти пиццы для клиента Kate в ценовом диапазоне 800-1000 рублей
-- с информацией о пиццериях и датах посещений
-- ============================================================================

-- ОПИСАНИЕ ЗАПРОСА:
-- Запрос соединяет 4 таблицы для получения полной информации о пиццах,
-- которые Kate могла заказать во время своих посещений пиццерий.
-- Используется цепочка INNER JOIN для связывания данных.

-- ЦЕПОЧКА СВЯЗЕЙ:
-- menu → pizzeria (узнаём название пиццерии)
--      → person_visits (находим посещения этой пиццерии)
--                     → person (определяем, кто посещал)

-- ============================================================================
-- ОСНОВНОЙ ЗАПРОС
-- ============================================================================

-- Выбираем 4 колонки для вывода
SELECT pizza_name,              -- название пиццы из таблицы menu
       price,                   -- цена пиццы из таблицы menu
       pizz.name AS pizzeria_name,  -- название пиццерии (с алиасом)
       visit.visit_date         -- дата посещения из person_visits

-- Начинаем с таблицы menu (основной источник данных о пиццах)
FROM menu

-- ============================================================================
-- JOIN 1: Связываем меню с пиццериями
-- ============================================================================
-- Цель: получить название пиццерии для каждой пиццы из меню
-- Связь: menu.pizzeria_id → pizzeria.id (внешний ключ → первичный ключ)

INNER JOIN pizzeria pizz
    ON pizz.id = menu.pizzeria_id


-- ============================================================================
-- JOIN 2: Связываем пиццерии с посещениями
-- ============================================================================
-- Цель: найти все посещения каждой пиццерии
-- Связь: pizzeria.id → person_visits.pizzeria_id
-- Важно: здесь связываем ТУ ЖЕ пиццерию (pizz.id = visit.pizzeria_id)

INNER JOIN person_visits visit
    ON pizz.id = visit.pizzeria_id


-- ============================================================================
-- JOIN 3: Связываем посещения с людьми
-- ============================================================================
-- Цель: определить, КТО посещал пиццерию
-- Связь: person_visits.person_id → person.id

INNER JOIN person client
    ON client.id = visit.person_id


-- ============================================================================
-- ФИЛЬТРАЦИЯ ДАННЫХ
-- ============================================================================
-- Применяем два условия для отбора нужных записей:

WHERE price BETWEEN 800 AND 1000    -- Условие 1: цена от 800 до 1000 рублей
  AND client.name = 'Kate'          -- Условие 2: только для клиента Kate

-- BETWEEN эквивалентен: price >= 800 AND price <= 1000

-- ============================================================================
-- СОРТИРОВКА РЕЗУЛЬТАТА
-- ============================================================================
-- Упорядочиваем вывод по трём колонкам для удобства чтения:
-- 1 = pizza_name (сначала по названию пиццы)
-- 2 = price (затем по цене)
-- 3 = pizzeria_name (затем по названию пиццерии)

ORDER BY 1, 2, 3;

-- ============================================================================
-- ОЖИДАЕМЫЙ РЕЗУЛЬТАТ:
-- Список пицц с ценами 800-1000₽ из пиццерий, которые посещала Kate,
-- с указанием дат посещений. Отсортирован по названию пиццы, цене и пиццерии.
-- ============================================================================

-- ============================================================================
-- ТЕХНИЧЕСКИЕ ДЕТАЛИ ДЛЯ ЗАЩИТЫ:
-- ============================================================================
-- 1. INNER JOIN используется, т.к. нам нужны только записи с совпадениями
--    во всех таблицах (пиццы с пиццериями, которые Kate посещала)
--
-- 2. Алиасы (pizz, visit, client) делают код читаемым и предотвращают
