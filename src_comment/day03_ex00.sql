--    пришлось бы писать pizzeria.name вместо pizz.name)
--
-- 3. Порядок JOIN важен: сначала получаем пиццерию, потом посещения,
--    потом человека — логическая цепочка от пиццы к клиенту
--
-- 4. WHERE фильтрует ПОСЛЕ соединения всех таблиц, оставляя только
--    нужные строки (Kate + диапазон цен)
--
-- 5. ORDER BY гарантирует упорядоченный вывод, что важно для читаемости
--    результата и соответствия требованиям задания
-- ============================================================================
```

