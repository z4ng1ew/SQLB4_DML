## ⚠️ Типичная ошибка

```sql
-- НЕПРАВИЛЬНО:
SELECT pizz.name  ← колонка называется "name"

-- Результат:
| pizza_name | price | name      | visit_date |
                      ↑
                   НЕПРАВИЛЬНО!

-- ПРАВИЛЬНО:
SELECT pizz.name AS pizzeria_name

-- Результат:
| pizza_name | price | pizzeria_name | visit_date |
                      ↑
                   ПРАВИЛЬНО!
```

---

## 🎯 Итоговое правило

### **Используй AS когда:**
- ✅ Имя колонки неоднозначное (`name`, `id`, `date`)
- ✅ Есть конфликты имён
- ✅ Вычисляемая колонка
- ✅ Требование задания

### **НЕ используй AS когда:**
- ❌ Имя колонки уже понятное и уникальное
- ❌ Нет конфликтов
- ❌ Задание не требует

---

## 🗣️ Для защиты говори так:

**"Я использую `AS pizzeria_name` для колонки `pizz.name`, потому что:**
1. **Название `name` слишком общее** — непонятно, чьё это имя
2. **Задание требует колонку `pizzeria_name`** в результате
3. **Это улучшает читаемость** — сразу видно, что это название пиццерии

**Для остальных колонок AS не нужен**, т.к. их названия уже достаточно информативны (`pizza_name`, `price`, `visit_date`)."

---

**Понятно теперь?** 😊 Алиас `AS pizzeria_name` — это для **переименования КОЛОНКИ в результате**, а `visit.` — это просто **указание ТАБЛИЦЫ** при обращении к колонке!