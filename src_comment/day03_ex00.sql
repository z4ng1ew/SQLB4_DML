/*
 * ОПИСАНИЕ ЗАДАЧИ:
 * Необходимо вывести список пицц с ценами в диапазоне 800-1000 рублей,
 * которые находятся в пиццериях, посещённых клиентом Kate.
 * 
 * ТРЕБОВАНИЯ К ВЫВОДУ:
 * - Название пиццы
