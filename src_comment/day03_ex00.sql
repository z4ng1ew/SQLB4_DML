## 🎓 Комментарий для УСТНОЙ защиты (что говорить)

**Сохрани это отдельно для подготовки:**

```markdown
## Объяснение запроса для защиты

**Задача:**
Найти пиццы в диапазоне 800-1000 рублей из пиццерий, которые посещала Kate.

**Структура запроса:**

1. **FROM menu** — начинаю с таблицы меню, т.к. там хранятся названия пицц и цены

2. **INNER JOIN pizzeria** — присоединяю пиццерии, чтобы узнать их названия
   - Связь: menu.pizzeria_id = pizzeria.id

3. **INNER JOIN person_visits** — добавляю информацию о посещениях
   - Связь: pizzeria.id = person_visits.pizzeria_id
   - Важно: соединяю по той же пиццерии, чтобы найти, кто её посещал

4. **INNER JOIN person** — определяю, кто именно посещал
   - Связь: person_visits.person_id = person.id

5. **WHERE** — фильтрую результат:
   - Цена от 800 до 1000 (BETWEEN включает границы)
   - Только Kate

6. **ORDER BY** — сортирую по названию пиццы, цене и пиццерии

**Почему INNER JOIN?**
Потому что нужны только пиццы из пиццерий, которые Kate действительно посещала.
Если бы использовал LEFT JOIN, получил бы также пиццерии, которые она не посещала.

**Результат:**
Список пицц с ценами, названиями пиццерий и датами посещений Kate.
```

