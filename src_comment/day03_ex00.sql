# 🔑 Зачем нужны алиасы? Разбор по полочкам

## 📊 Давай разберём ТВОй запрос

```sql
SELECT pizza_name,
       price,
       pizz.name AS pizzeria_name,  ← АЛИАС КОЛОНКИ
       visit.visit_date             ← НЕ алиас! Просто обращение
```

---

## 1️⃣ `pizz.name AS pizzeria_name` — ЗАЧЕМ?

### **Проблема БЕЗ алиаса:**

```sql
SELECT pizza_name,
       price,
       pizz.name,        ← без AS pizzeria_name
       visit.visit_date
FROM ...
```

**Результат:**
```
┌──────────────┬───────┬───────────┬────────────┐
│ pizza_name   │ price │ name      │ visit_date │  ← "name" непонятно!
├──────────────┼───────┼───────────┼────────────┤
│ cheese pizza │ 900   │ Pizza Hut │ 2022-01-03 │
└──────────────┴───────┴───────────┴────────────┘
                         ↑
                    ЧТО ЭТО ЗА NAME???
```

**Проблемы:**
- ❌ Непонятно, что означает колонка `name` (имя чего? пиццы? человека? пиццерии?)
- ❌ Если бы в запросе была ещё одна таблица с колонкой `name`, была бы путаница

---

### **С алиасом (правильно):**

```sql
SELECT pizza_name,
       price,
       pizz.name AS pizzeria_name,  ← переименовали!
       visit.visit_date
FROM ...
```

**Результат:**
```
┌──────────────┬───────┬───────────────┬────────────┐
│ pizza_name   │ price │ pizzeria_name │ visit_date │  ← ПОНЯТНО!
├──────────────┼───────┼───────────────┼────────────┤
│ cheese pizza │ 900   │ Pizza Hut     │ 2022-01-03 │
└──────────────┴───────┴───────────────┴────────────┘
                         ↑
                    Ясно — это название пиццерии!
```

**Преимущества:**
- ✅ Сразу понятно: `pizzeria_name` = название пиццерии
- ✅ Нет путаницы с другими колонками `name`
- ✅ Результат самодокументируемый

---

## 2️⃣ `visit.visit_date` — ЭТО НЕ АЛИАС!

### **Разбор:**

```sql
visit.visit_date
  ↑       ↑
  |       └─ название колонки в таблице person_visits
  └───────── алиас ТАБЛИЦЫ (не колонки!)
```

**Это просто обращение к колонке через алиас таблицы!**

---

### **Аналогия с алиасом колонки:**

```sql
-- БЕЗ алиаса колонки:
SELECT visit.visit_date  ← в результате будет "visit_date"

-- С алиасом колонки:
SELECT visit.visit_date AS visit_date_renamed  ← в результате будет "visit_date_renamed"
```

**В твоём случае:**
```sql
visit.visit_date  ← НЕ переименовывается, остаётся "visit_date"
```

---

## 🎯 Когда НУЖЕН алиас колонки (AS)?

### **Случай 1: Колонка называется неоднозначно**

```sql
-- ПЛОХО:
SELECT name FROM pizzeria;  ← "name" — это что?

-- ХОРОШО:
SELECT name AS pizzeria_name FROM pizzeria;  ← понятно!
```

---

### **Случай 2: Несколько колонок с одинаковым именем**

```sql
-- КОНФЛИКТ (ошибка в некоторых случаях):
SELECT person.name, pizzeria.name
FROM person_visits
JOIN person ON ...
JOIN pizzeria ON ...;

-- Результат:
┌──────┬──────┐
│ name │ name │  ← две колонки "name"! Путаница!
└──────┴──────┘

-- ПРАВИЛЬНО:
SELECT person.name AS client_name,
       pizzeria.name AS pizzeria_name
FROM ...;

-- Результат:
┌─────────────┬───────────────┐
│ client_name │ pizzeria_name │  ← понятно!
└─────────────┴───────────────┘
```

---

### **Случай 3: Вычисляемые колонки**

```sql
-- БЕЗ алиаса (некрасиво):
SELECT price * 0.9
FROM menu;

-- Результат:
┌────────┐
│ ?column? │  ← PostgreSQL не знает, как назвать!
└────────┘

-- С алиасом (правильно):
SELECT price * 0.9 AS discounted_price
FROM menu;

-- Результат:
┌──────────────────┐
│ discounted_price │  ← понятно!
└──────────────────┘
```

---

### **Случай 4: Требования задания**

**В твоём задании:**
> Пример ожидаемого результата с названиями колонок приведен ниже:

```
| pizza_name | price | pizzeria_name | visit_date |
```

**Значит, колонка ДОЛЖНА называться `pizzeria_name`, а не `name`!**

```sql
-- Без алиаса (не соответствует заданию):
SELECT pizz.name  ← результат: колонка "name" ❌

-- С алиасом (соответствует заданию):
SELECT pizz.name AS pizzeria_name  ← результат: "pizzeria_name" ✅
```

---

## 🔍 Когда алиас НЕ НУЖЕН?

### **Случай 1: Колонка уже хорошо названа**

```sql
SELECT pizza_name,  ← уже понятно, что это название пиццы
       price        ← понятно, что это цена
FROM menu;

-- НЕ нужно:
SELECT pizza_name AS pizza_name,  ← избыточно!
       price AS price             ← избыточно!
```

---

### **Случай 2: Нет конфликтов имён**

```sql
SELECT visit_date  ← только одна колонка visit_date в запросе
FROM person_visits;

-- НЕ нужно:
SELECT visit_date AS visit_date  ← дублирование!
```

---

## 📋 Таблица: Когда использовать AS

| Ситуация | Нужен ли AS? | Пример |
|----------|--------------|--------|
| Неоднозначное имя (`name`) | ✅ ДА | `name AS pizzeria_name` |
| Конфликт имён | ✅ ДА | `p1.name AS name1, p2.name AS name2` |
| Вычисления | ✅ ДА | `price * 0.9 AS discount` |
| Требования задания | ✅ ДА | `name AS pizzeria_name` |
| Уникальное понятное имя | ❌ НЕТ | `pizza_name` (без AS) |
| Нет конфликтов | ❌ НЕТ | `visit_date` (без AS) |

---

## 💡 Твой запрос — разбор

```sql
SELECT pizza_name,                    -- ✅ понятно, AS не нужен
       price,                         -- ✅ понятно, AS не нужен
       pizz.name AS pizzeria_name,    -- ✅ НУЖЕН! "name" неоднозначно
       visit.visit_date               -- ✅ понятно, AS не нужен
```

**Почему `AS pizzeria_name` нужен:**
1. `name` — слишком общее, непонятно чьё имя
2. Задание требует колонку `pizzeria_name`
3. Улучшает читаемость результата

**Почему `visit.visit_date` без AS:**
1. `visit_date` уже понятное название
2. Нет конфликтов с другими колонками
3. Префикс `visit.` нужен для указания таблицы, но не меняет название колонки в результате

---

## 🎨 Альтернативные варианты

### **Вариант 1: Всё с алиасами (избыточно, но допустимо)**

```sql
SELECT pizza_name AS pizza_name,           -- избыточно
       price AS price,                     -- избыточно
       pizz.name AS pizzeria_name,         -- нужен
       visit.visit_date AS visit_date      -- избыточно
```

### **Вариант 2: Минимум алиасов (твой вариант — оптимально)**

```sql
SELECT pizza_name,                         -- без AS
       price,                              -- без AS
       pizz.name AS pizzeria_name,         -- с AS (нужен!)
       visit.visit_date                    -- без AS
```

### **Вариант 3: Без алиасов (плохо — не соответствует заданию)**

```sql
SELECT pizza_name,
       price,
       pizz.name,        ← колонка будет "name" ❌
       visit.visit_date
```

