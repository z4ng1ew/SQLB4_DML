## 💡 Комментированный код

```sql
-- ============================================================================
-- SQL Bootcamp Day 03 — Exercise 06
-- ============================================================================
-- Задание: Найти пиццы с одинаковым названием и ценой из разных пиццерий
-- Техника: SELF JOIN (самосоединение)
-- ============================================================================

SELECT 
    menu1.pizza_name,                -- Название пиццы
    pizz1.name AS pizzeria_name_1,   -- Первая пиццерия
    pizz2.name AS pizzeria_name_2,   -- Вторая пиццерия
    menu1.price                      -- Цена (одинаковая для обеих)

-- Таблица menu соединяется сама с собой
FROM menu menu1              -- Первый "экземпляр" (первая пицца из пары)

INNER JOIN menu menu2        -- Второй "экземпляр" (вторая пицца из пары)
    -- КРИТИЧЕСКИЕ УСЛОВИЯ:
    ON menu1.id <> menu2.id                     -- 1. Разные записи
    AND menu1.pizza_name = menu2.pizza_name     -- 2. Одинаковое название
    AND menu1.price = menu2.price               -- 3. Одинаковая цена
    AND menu1.pizzeria_id > menu2.pizzeria_id   -- 4. Убираем дубликаты
    
    -- Условие 4 объяснение:
    -- Без него каждая пара появится ДВАЖДЫ: (A,B) и (B,A)
    -- С ним: только одна комбинация, где ID первой > ID второй

-- Получаем название первой пиццерии
INNER JOIN pizzeria pizz1 ON menu1.pizzeria_id = pizz1.id

-- Получаем название второй пиццерии  
INNER JOIN pizzeria pizz2 ON menu2.pizzeria_id = pizz2.id

ORDER BY 1;  -- Сортировка по названию пиццы
```

