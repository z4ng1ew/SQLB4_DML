# 📌 `menu1.pizza_name` — Что это?

## 🎯 Краткий ответ

**`menu1.pizza_name`** — это обращение к колонке `pizza_name` из таблицы `menu` с алиасом (псевдонимом) `menu1`.

---

## 📊 Разбор по частям

| Часть | Что означает |
|-------|--------------|
| `menu1` | **Алиас** (псевдоним) таблицы `menu` |
| `.` | **Разделитель** между таблицей и колонкой |
| `pizza_name` | **Имя колонки** в таблице |

---

## 💡 Пример из кода

```sql
FROM menu menu1
--        ↑      ↑
--     таблица  алиас

SELECT menu1.pizza_name
--     ↑            ↑
--   алиас       колонка
```

**Читается как:** *"pizza_name из таблицы menu1"*

---

## 🔍 Зачем нужен алиас `menu1`?

### Причина 1: **SELF JOIN** (таблица соединяется сама с собой)

```sql
FROM menu menu1
INNER JOIN menu menu2 ON menu1.id <> menu2.id
```

**Без алиасов было бы НЕПОНЯТНО:**
```sql
-- ❌ ПЛОХО: Какая таблица menu имеется в виду?
FROM menu
INNER JOIN menu ON menu.id <> menu.id  ← БЕСМЫСЛЕННО!
```

**С алиасами ЯСНО:**
```sql
-- ✅ ХОРОШО: menu1 — первая копия, menu2 — вторая копия
FROM menu menu1
INNER JOIN menu menu2 ON menu1.id <> menu2.id
--                        ↑         ↑
--                   первая копия  вторая копия
```

---

### Причина 2: **Избежание конфликта имён**

Когда в запросе **две копии одной таблицы**, SQL должен понимать, к какой копии вы обращаетесь:

```
┌─────────────────────────────────────────────────────────────────┐
│                        menu (menu1)                             │
│  ┌─────┬─────────────┬──────────────┬───────┐                   │
│  │ id  │ pizzeria_id │ pizza_name   │ price │                   │
│  ├─────┼─────────────┼──────────────┼───────┤                   │
│  │ 9   │ 5           │ cheese pizza │ 700   │ ← menu1           │
│  └─────┴─────────────┴──────────────┴───────┘                   │
│                                                                 │
│                        menu (menu2)                             │
│  ┌──────────────────┬──────────────┬───────┐                    │
│  │ id  │ pizzeria_id │ pizza_name   │ price │                   │
│  ├─────┼─────────────┼──────────────┼───────┤                   │
│  │ 12  │ 4           │ cheese pizza │ 700   │ ← menu2           │
│  └─────┴─────────────┴──────────────┴───────┘                   │
└─────────────────────────────────────────────────────────────────┘

menu1.pizza_name → "cheese pizza" (из первой копии)
menu2.pizza_name → "cheese pizza" (из второй копии)
```

---

## 📋 Полная запись vs Краткая запись

| Запись | Что означает | Когда использовать |
|--------|--------------|-------------------|
| `menu1.pizza_name` | Колонка `pizza_name` из алиаса `menu1` | ✅ Всегда (явно и понятно) |
| `pizza_name` | Колонка `pizza_name` из любой таблицы | ⚠️ Только если колонка уникальна |
| `menu.pizza_name` | Колонка `pizza_name` из таблицы `menu` | ⚠️ Если нет алиаса |

---

## ⚠️ Что будет, если не указать алиас?

```sql
-- ❌ ОШИБКА: Неясно, из какой таблицы брать pizza_name
SELECT pizza_name
FROM menu menu1
INNER JOIN menu menu2 ON menu1.id <> menu2.id
-- ERROR: column reference "pizza_name" is ambiguous

-- ✅ ПРАВИЛЬНО: Явно указываем, из какой копии таблицы
SELECT menu1.pizza_name
FROM menu menu1
INNER JOIN menu menu2 ON menu1.id <> menu2.id
```

**Ошибка `ambiguous`** означает **"неоднозначное"** — SQL не понимает, к какой таблице обращаться.

