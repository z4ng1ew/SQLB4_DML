/*
 * ВАРИАНТ 1: С условием <> вместо > (с дубликатами)
 * ---------------------------------------------------------
 * SELECT menu1.pizza_name,
 *        pizz1.name AS pizzeria_name_1,
 *        pizz2.name AS pizzeria_name_2,
 *        menu1.price
 * FROM menu menu1
 * INNER JOIN menu menu2
 *     ON menu1.id <> menu2.id
 *     AND menu1.pizza_name = menu2.pizza_name
 *     AND menu1.price = menu2.price
 *     AND menu1.pizzeria_id <> menu2.pizzeria_id  -- <> вместо >
 * INNER JOIN pizzeria pizz1 ON menu1.pizzeria_id = pizz1.id
 * INNER JOIN pizzeria pizz2 ON menu2.pizzeria_id = pizz2.id
 * ORDER BY 1;
 * 
 * РЕЗУЛЬТАТ: Будут зеркальные дубликаты:
 *   (Best Pizza, Papa Johns) и (Papa Johns, Best Pizza)
 * 
 * МИНУС: В 2 раза больше строк, сложнее анализировать
 */

/*
 * ВАРИАНТ 2: С MIN/MAX для нормализации порядка
 * ---------------------------------------------------------
 * SELECT pizza_name,
 *        LEAST(pizzeria_name_1, pizzeria_name_2) AS pizzeria_name_1,
 *        GREATEST(pizzeria_name_1, pizzeria_name_2) AS pizzeria_name_2,
 *        price
 * FROM (
 *     SELECT menu1.pizza_name,
 *            pizz1.name AS pizzeria_name_1,
 *            pizz2.name AS pizzeria_name_2,
 *            menu1.price
 *     FROM menu menu1
 *     INNER JOIN menu menu2 ON ...
 * ) AS subquery
 * ORDER BY 1;
 * 
 * ПЛЮС: Гарантирует одинаковый порядок названий
 * МИНУС: Сложнее, требует подзапроса
 */

-- ============================================================================
-- ОТВЕТЫ НА ВОПРОСЫ ДЛЯ ЗАЩИТЫ
-- ============================================================================

/*
 * ВОПРОС 1: Зачем SELF JOIN, а не обычный JOIN?
 * ОТВЕТ: SELF JOIN нужен для сравнения строк внутри одной таблицы.
 *        Обычный JOIN соединяет разные таблицы, а нам нужно сравнить
 *        menu с menu (одинаковые пиццы в разных пиццериях).
 * 
 * ВОПРОС 2: Почему menu1.id <> menu2.id?
 * ОТВЕТ: Чтобы исключить сравнение записи с самой собой.
 *        Без этого условия каждая пицца совпадёт сама с собой,
 *        что даст бессмысленные результаты.
 * 
 * ВОПРОС 3: Зачем условие menu1.pizzeria_id > menu2.pizzeria_id?
 * ОТВЕТ: Две функции:
 *        1. Гарантирует разные пиццерии (не сравниваем внутри одной)
 *        2. Предотвращает зеркальные дубликаты (A,B и B,A)
 *        Оператор > вместо <> выбирает только одну направленность пары.
 * 
 * ВОПРОС 4: Почему два JOIN с pizzeria?
 * ОТВЕТ: Нужно получить названия ОБЕИХ пиццерий в паре.
 *        menu1.pizzeria_id → pizz1.name (первая пиццерия)
 *        menu2.pizzeria_id → pizz2.name (вторая пиццерия)
 *        Один JOIN дал бы только одну пиццерию.
 * 
 * ВОПРОС 5: Что означает ORDER BY 1?
 * ОТВЕТ: Сортировка по первой колонке в SELECT (pizza_name).
 *        Это то же самое, что ORDER BY menu1.pizza_name.
 * 
 * ВОПРОС 6: Может ли одна пиццерия встретиться дважды в одной строке?
 * ОТВЕТ: Нет, условие menu1.pizzeria_id > menu2.pizzeria_id гарантирует,
 *        что pizzeria_id разные, значит и пиццерии разные.
 * 
 * ВОПРОС 7: Зачем алиасы menu1, menu2, pizz1, pizz2?
 * ОТВЕТ: При SELF JOIN обязательно нужны разные алиасы, чтобы
 *        различать "левую" и "правую" часть сравнения.
 *        Без алиасов SQL не поймёт, к какой копии таблицы обращаться.
 * 
 * ВОПРОС 8: Что будет, если убрать условие >?
 * ОТВЕТ: Появятся зеркальные дубликаты:
 *        (Best Pizza, Papa Johns) и (Papa Johns, Best Pizza)
 *        Результат увеличится в 2 раза, анализ усложнится.
 */

-- ============================================================================
-- КЛЮЧЕВЫЕ ВЫВОДЫ
-- ============================================================================

/*
 * 1. SELF JOIN — мощный инструмент для сравнения строк внутри таблицы
 * 
 * 2. Условие > вместо <> предотвращает дубликаты пар (A,B) и (B,A)
 * 
 * 3. При SELF JOIN всегда нужны алиасы для различения копий таблицы
 * 
 * 4. Два JOIN с одной таблицей (pizzeria) нужны для получения
 *    названий обеих пиццерий в паре
 * 
 * 5. ORDER BY 1 — краткая запись сортировки по первой колонке SELECT
 */

