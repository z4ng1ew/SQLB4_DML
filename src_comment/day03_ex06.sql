## 🍕 Теперь про пиццы

### **У нас есть 2 пиццерии с одинаковой пиццей:**

```
Строка 12: Papa Johns  - cheese pizza, 700₽
Строка 16: Best Pizza  - cheese pizza, 700₽
```

### **SELF JOIN пытается сравнить ВСЁ со ВСЕМ:**

```
Комбинация 1: Строка 12 со строкой 12
Комбинация 2: Строка 12 со строкой 16  ← Это пара пиццерий!
Комбинация 3: Строка 16 со строкой 12  ← Та же пара, но задом наперёд!
Комбинация 4: Строка 16 со строкой 16
```

---

### **Условие 1: `menu1.id <> menu2.id` (не сравнивай строку саму с собой)**

```
Комбинация 1: 12 с 12   → 12 ≠ 12? ❌ НЕТ → УБРАЛИ
Комбинация 2: 12 с 16   → 12 ≠ 16? ✅ ДА  → ОСТАВЛЯЕМ
Комбинация 3: 16 с 12   → 16 ≠ 12? ✅ ДА  → ОСТАВЛЯЕМ (дубликат!)
Комбинация 4: 16 с 16   → 16 ≠ 16? ❌ НЕТ → УБРАЛИ
```

**Проблема:** Комбинации 2 и 3 - это **ОДНА И ТА ЖЕ ИНФОРМАЦИЯ**!

```
Комбинация 2: Papa Johns & Best Pizza
Комбинация 3: Best Pizza & Papa Johns  ← Та же пара!
```

---

### **Условие 2: `menu1.pizzeria_id > menu2.pizzeria_id`**

```
Papa Johns имеет pizzeria_id = 4
Best Pizza имеет pizzeria_id = 5

Комбинация 2: 
menu1 = строка 12 (pizzeria_id=4)
menu2 = строка 16 (pizzeria_id=5)
Вопрос: 4 > 5? ❌ НЕТ → УБИРАЕМ

Комбинация 3:
menu1 = строка 16 (pizzeria_id=5)
menu2 = строка 12 (pizzeria_id=4)
Вопрос: 5 > 4? ✅ ДА → ОСТАВЛЯЕМ
```

**Результат:** Только **ОДНА** пара!

---

## 📝 **САМОЕ ПРОСТОЕ ОБЪЯСНЕНИЕ**

### **Два условия решают ДВЕ разные проблемы:**

**Проблема 1:** Строка сравнивается САМА С СОБОЙ
```
Строка 12 ↔ Строка 12  ❌ Глупо!
```
**Решение:** `menu1.id <> menu2.id` ✅

---

**Проблема 2:** Каждая пара появляется ДВАЖДЫ
```
Строка 12 → Строка 16  } 
Строка 16 → Строка 12  } ← Это ОДНО И ТО ЖЕ!
```
**Решение:** `menu1.pizzeria_id > menu2.pizzeria_id` ✅

---

## 🎯 В двух словах

```
menu1.id <> menu2.id
↓
Убирает: "строка сравнивается САМА С СОБОЙ"

menu1.pizzeria_id > menu2.pizzeria_id
↓
Убирает: "пары-близнецы (A,B) и (B,A)"
```

