# 🔍 Детальное объяснение Задания 06

## 🎯 Цель запроса

**Найти пиццы с одинаковым названием и одинаковой ценой, но из РАЗНЫХ пиццерий**

Например:
- "cheese pizza" за 700₽ продаётся и в Papa Johns, и в Best Pizza

---

## 🧩 Структура запроса: SELF JOIN (Самосоединение)

### **Главная идея:**

Таблица `menu` **соединяется сама с собой**, чтобы сравнить каждую пиццу с каждой другой пиццей из этой же таблицы.

```
     menu                        menu
  (оригинал)               (та же таблица!)
┌────┬────────┬───────┐   ┌────┬────────┬───────┐
│ 12 │ cheese │ 700₽  │   │ 16 │ cheese │ 700₽  │
│    │Papa J. │       │ ←→│    │Best P. │       │
└────┴────────┴───────┘   └────┴────────┴───────┘
      menu1                     menu2
   (1-я копия)               (2-я копия)
   
Сравниваем: одинаковые название и цена? ✅
           но разные пиццерии? ✅
```

---

## 📋 Пошаговый разбор кода

### **Шаг 1: SELECT — Что выводим**

```sql
SELECT menu1.pizza_name,              -- Название пиццы (одно для обеих)
       pizz1.name AS pizzeria_name_1, -- Первая пиццерия
       pizz2.name AS pizzeria_name_2, -- Вторая пиццерия
       menu1.price                    -- Цена (одинаковая для обеих)
```

**Результат будет таким:**
```
┌──────────────┬────────────────┬────────────────┬───────┐
│ pizza_name   │ pizzeria_name_1│ pizzeria_name_2│ price │
├──────────────┼────────────────┼────────────────┼───────┤
│ cheese pizza │ Best Pizza     │ Papa Johns     │ 700   │
│ pepperoni    │ Best Pizza     │ DinoPizza      │ 800   │
│ supreme pizza│ Best Pizza     │ DoDo Pizza     │ 850   │
└──────────────┴────────────────┴────────────────┴───────┘
```

---

### **Шаг 2: FROM — SELF JOIN начинается здесь**

```sql
FROM menu menu1
     ────┬────
         │
    Создаём ПЕРВУЮ копию таблицы menu
    Алиас: menu1
```

**menu1** будет содержать **первую пиццу из пары**

---

### **Шаг 3: INNER JOIN — Соединяем таблицу саму с собой**

```sql
INNER JOIN menu menu2
           ────┬────
               │
          Создаём ВТОРУЮ копию той же таблицы menu
          Алиас: menu2
```

**menu2** будет содержать **вторую пиццу из пары**

**Визуализация:**

```
Физически это ОДНА таблица menu:
┌────┬─────────────┬──────────────┬───────┐
│ id │ pizzeria_id │ pizza_name   │ price │
├────┼─────────────┼──────────────┼───────┤
│ 12 │ 4           │ cheese pizza │ 700   │
│ 16 │ 5           │ cheese pizza │ 700   │
│ 17 │ 5           │ pepperoni    │ 800   │
│ 6  │ 6           │ pepperoni    │ 800   │
└────┴─────────────┴──────────────┴───────┘

Логически работаем как с ДВУМЯ таблицами:

menu1 (первая копия)     menu2 (вторая копия)
┌────┬────────┬─────┐   ┌────┬────────┬─────┐
│ 12 │ cheese │ 700 │   │ 16 │ cheese │ 700 │
│ 16 │ cheese │ 700 │   │ 12 │ cheese │ 700 │
│ 17 │ pepper │ 800 │   │ 6  │ pepper │ 800 │
│ 6  │ pepper │ 800 │   │ 17 │ pepper │ 800 │
└────┴────────┴─────┘   └────┴────────┴─────┘
```

---

### **Шаг 4: Условия ON — 4 критических фильтра**

```sql
ON menu1.id <> menu2.id                     -- Условие 1
   AND menu1.pizza_name = menu2.pizza_name  -- Условие 2
   AND menu1.price = menu2.price            -- Условие 3
   AND menu1.pizzeria_id > menu2.pizzeria_id -- Условие 4
```

#### **Условие 1: `menu1.id <> menu2.id`**

**Смысл:** Не сравнивай строку саму с собой!

```
❌ БЕЗ этого условия:
menu1.id=12, menu2.id=12  ← Это одна и та же строка!

✅ С условием:
menu1.id=12, menu2.id=16  ← Разные строки ✓
```

---

#### **Условие 2: `menu1.pizza_name = menu2.pizza_name`**

**Смысл:** Ищем пиццы с ОДИНАКОВЫМ названием

```
✅ Проходит:
menu1: "cheese pizza"
menu2: "cheese pizza"  ← Совпадает!

❌ Не проходит:
menu1: "cheese pizza"
menu2: "pepperoni pizza"  ← Разные названия
```

---

#### **Условие 3: `menu1.price = menu2.price`**

**Смысл:** И с ОДИНАКОВОЙ ценой

```
✅ Проходит:
menu1: cheese pizza, 700₽
menu2: cheese pizza, 700₽  ← Одинаковая цена!

❌ Не проходит:
menu1: cheese pizza, 700₽
menu2: cheese pizza, 900₽  ← Разные цены
```

---

#### **Условие 4: `menu1.pizzeria_id > menu2.pizzeria_id`** ⭐ **КРИТИЧЕСКОЕ!**

**Смысл:** Убирает дубликаты пар

**Проблема без этого условия:**

```
Найдутся ДВЕ одинаковые пары:

Пара 1:
┌──────────────┬─────────────┬─────────────┬───────┐
│ pizza_name   │ pizz_name_1 │ pizz_name_2 │ price │
├──────────────┼─────────────┼─────────────┼───────┤
│ cheese pizza │ Best Pizza  │ Papa Johns  │ 700   │
└──────────────┴─────────────┴─────────────┴───────┘

Пара 2:
┌──────────────┬─────────────┬─────────────┬───────┐
│ pizza_name   │ pizz_name_1 │ pizz_name_2 │ price │
├──────────────┼─────────────┼─────────────┼───────┤
│ cheese pizza │ Papa Johns  │ Best Pizza  │ 700   │
└──────────────┴─────────────┴─────────────┴───────┘

Это ОДНА И ТА ЖЕ информация, просто в разном порядке!
```

**Решение:**

```sql
menu1.pizzeria_id > menu2.pizzeria_id
```

Берём пары только где **ID первой пиццерии БОЛЬШЕ ID второй**

**Пример:**

```
Best Pizza: pizzeria_id = 5
Papa Johns: pizzeria_id = 4

Проверка пары 1:
menu1: Best Pizza (5), menu2: Papa Johns (4)
5 > 4? ✅ ДА → ВКЛЮЧАЕМ эту пару

Проверка пары 2:
menu1: Papa Johns (4), menu2: Best Pizza (5)
4 > 5? ❌ НЕТ → ИСКЛЮЧАЕМ (это дубликат)

Результат: только ОДНА пара!
```

---

### **Шаг 5: JOIN с pizzeria — Получаем названия**

```sql
INNER JOIN pizzeria pizz1 ON menu1.pizzeria_id = pizz1.id
INNER JOIN pizzeria pizz2 ON menu2.pizzeria_id = pizz2.id
```

**Зачем ДВА JOIN с pizzeria?**

Потому что **menu1** и **menu2** ссылаются на **РАЗНЫЕ пиццерии!**

```
menu1.pizzeria_id = 5  →  pizz1  →  "Best Pizza"
menu2.pizzeria_id = 4  →  pizz2  →  "Papa Johns"
```

**Визуализация:**

```
menu1                    pizzeria (pizz1)
┌────┬─────────────┐    ┌────┬────────────┐
│ 16 │ pizzeria=5  │───→│ 5  │ Best Pizza │
└────┴─────────────┘    └────┴────────────┘

menu2                    pizzeria (pizz2)
┌────┬─────────────┐    ┌────┬────────────┐
│ 12 │ pizzeria=4  │───→│ 4  │ Papa Johns │
└────┴─────────────┘    └────┴────────────┘
```

