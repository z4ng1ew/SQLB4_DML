1. Иван → Иван     ❌ УБРАЛИ!
2. Иван → Мария    ✅
3. Иван → Петр     ✅
4. Мария → Иван    ✅ (повтор!)
5. Мария → Мария   ❌ УБРАЛИ!
6. Мария → Петр    ✅
7. Петр → Иван     ✅ (повтор!)
8. Петр → Мария    ✅ (повтор!)
9. Петр → Петр     ❌ УБРАЛИ!
```

**Что получилось:**
- ✅ Убрали глупость (сам с собой)
- ❌ НО! Каждая пара всё ещё дважды: (Иван→Мария) и (Мария→Иван)

**Осталось 6 пар, но реально только 3 уникальных!**

---

## ✅✅ **С обоими условиями** `id <> id` + `id1 > id2`:

```
Дадим людям номера:
Иван = 1
Мария = 2
Петр = 3

Правило: "Берём пару только если первый номер БОЛЬШЕ второго"

2. Иван(1) → Мария(2)    1 > 2? ❌ НЕТ → УБИРАЕМ
3. Иван(1) → Петр(3)     1 > 3? ❌ НЕТ → УБИРАЕМ
4. Мария(2) → Иван(1)    2 > 1? ✅ ДА → ОСТАВЛЯЕМ
6. Мария(2) → Петр(3)    2 > 3? ❌ НЕТ → УБИРАЕМ
7. Петр(3) → Иван(1)     3 > 1? ✅ ДА → ОСТАВЛЯЕМ
8. Петр(3) → Мария(2)    3 > 2? ✅ ДА → ОСТАВЛЯЕМ
```

**ИТОГО: 3 пары** (ровно столько, сколько нужно!)

```
✅ Мария → Иван
✅ Петр → Иван
✅ Петр → Мария
```

Каждое рукопожатие учтено **ОДИН РАЗ**!

