-- ↑↑↑
-- КОММЕНТАРИЙ: Получаем название второй пиццерии
-- - menu2.pizzeria_id = pizz2.id: связываем menu2 с pizzeria
-- - pizz2: вторая копия таблицы pizzeria (алиас)
-- - INNER JOIN: берём только существующие пиццерии
-- 
-- ПОТОК ДАННЫХ:
--   menu2 (pizzeria_id=4)
--   ↓ JOIN
--   pizzeria (id=4, name='Papa Johns')
--   ↓
--   Результат: 'Papa Johns' в колонку pizzeria_name_2
-- 
-- ЗАЧЕМ ДВА JOIN С PIZZERIA:
-- - Нужно получить названия ОБЕИХ пиццерий в паре
-- - Один JOIN дал бы только одну пиццерию
-- - Две разные копии (pizz1, pizz2) для двух разных pizzeria_id

-- ============================================================================
-- ЧАСТЬ 4: СОРТИРОВКА РЕЗУЛЬТАТА
-- ============================================================================

ORDER BY 1;
