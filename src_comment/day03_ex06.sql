 <> — Оператор "НЕ РАВНО" в SQL

    ON menu1.id <> menu2.id
-- ↑↑↑
-- КОММЕНТАРИЙ: Условие 1 — разные записи меню
-- - menu1.id <> menu2.id: исключаем сравнение записи с самой собой
-- - Без этого условия каждая пицца совпадёт сама с собой
-- - Оператор <> означает "не равно" (синоним !=)
-- 
-- ПРИМЕР:
--   menu1.id=9, menu2.id=9 → НЕ подходит (одна и та же запись)
--   menu1.id=9, menu2.id=12 → ПОДХОДИТ (разные записи)
-- 
-- ЗАЧЕМ ЭТО НУЖНО:
-- - Предотвращает дублирование (пицца не должна совпадать сама с собой)
-- - Уменьшает количество строк в результате

    AND menu1.pizza_name = menu2.pizza_name
-- ↑↑↑
-- КОММЕНТАРИЙ: Условие 2 — одинаковое название пиццы
-- - menu1.pizza_name = menu2.pizza_name: названия должны совпадать
-- - Сравниваем только одинаковые пиццы (cheese с cheese, не cheese с pepperoni)
-- 
-- ПРИМЕР:
--   menu1: 'cheese pizza', menu2: 'cheese pizza' → ПОДХОДИТ ✅
--   menu1: 'cheese pizza', menu2: 'pepperoni pizza' → НЕ ПОДХОДИТ ❌
-- 
-- ЗАЧЕМ ЭТО НУЖНО:
-- - Ищем именно одинаковые пиццы в разных местах
-- - Разные названия не имеют смысла сравнивать по цене

    AND menu1.price = menu2.price
-- ↑↑↑
-- КОММЕНТАРИЙ: Условие 3 — одинаковая цена
-- - menu1.price = menu2.price: цены должны совпадать
-- - Это ключевое условие задания (price-similarity)
-- 
-- ПРИМЕР:
--   menu1: 700, menu2: 700 → ПОДХОДИТ ✅
--   menu1: 700, menu2: 900 → НЕ ПОДХОДИТ ❌
-- 
-- ЗАЧЕМ ЭТО НУЖНО:
-- - Задание требует найти пиццы с одинаковой ценой
-- - Позволяет выявить ценовую политику пиццерий

    AND menu1.pizzeria_id > menu2.pizzeria_id
-- ↑↑↑
-- КОММЕНТАРИЙ: Условие 4 — разные пиццерии + предотвращение дубликатов
-- - menu1.pizzeria_id > menu2.pizzeria_id: пиццерии должны быть разными
-- - Оператор > (больше) вместо <> (не равно) имеет дополнительный смысл
-- 
-- ДВЕ ФУНКЦИИ ЭТОГО УСЛОВИЯ:
-- 
-- 1. Разные пиццерии:
--    - menu1.pizzeria_id ≠ menu2.pizzeria_id
--    - Исключает сравнение пицц из одной пиццерии
-- 
-- 2. Предотвращение дубликатов (ключевое!):
--    - Без этого условия пары будут дублироваться:
--      (Best Pizza, Papa Johns) и (Papa Johns, Best Pizza)
--    - С условием > получаем только одну направленность:
--      (Papa Johns, Best Pizza) где 4 > 5 = FALSE (не попадёт)
--      (Best Pizza, Papa Johns) где 5 > 4 = TRUE (попадёт)
-- 
-- ПРИМЕР:
--   menu1.pizzeria_id=5, menu2.pizzeria_id=4 → 5>4=TRUE ✅
--   menu1.pizzeria_id=4, menu2.pizzeria_id=5 → 4>5=FALSE ❌
--   menu1.pizzeria_id=5, menu2.pizzeria_id=5 → 5>5=FALSE ❌
-- 
-- ЗАЧЕМ ЭТО НУЖНО:
-- - Экономит место в результате (нет зеркальных дублей)
-- - Упрощает анализ данных

-- ============================================================================
-- ЧАСТЬ 3: JOIN С ТАБЛИЦЕЙ PIZZERIA (ДВАЖДЫ)
-- ============================================================================

INNER JOIN pizzeria pizz1 
    ON menu1.pizzeria_id = pizz1.id
-- ↑↑↑
-- КОММЕНТАРИЙ: Получаем название первой пиццерии
-- - menu1.pizzeria_id = pizz1.id: связываем menu1 с pizzeria
-- - pizz1: первая копия таблицы pizzeria (алиас)
-- - INNER JOIN: берём только существующие пиццерии
-- 
-- ПОТОК ДАННЫХ:
--   menu1 (pizzeria_id=5)
--   ↓ JOIN
--   pizzeria (id=5, name='Best Pizza')
--   ↓
--   Результат: 'Best Pizza' в колонку pizzeria_name_1
-- 
-- ПРИМЕР ДАННЫХ pizzeria:
-- ┌─────┬─────────────────┬────────┐
-- │ id  │ name            │ rating │
-- ├─────┼─────────────────┼────────┤
-- │ 4   │ Papa Johns      │ 4.9    │
-- │ 5   │ Best Pizza      │ 2.3    │
-- └─────┴─────────────────┴────────┘

INNER JOIN pizzeria pizz2 
