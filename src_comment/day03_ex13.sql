## Объяснение скрипта для защиты

**Задача:**
Откатить изменения, сделанные в заданиях 07, 11, 12:
- Удалить все заказы от 25.02.2022 (задание 12)
- Удалить greek pizza из меню (задания 07 и 11)

**Структура скрипта (4 шага):**

### **Шаг 1: DELETE person_order (КРИТИЧЕСКИ ВАЖЕН ПОРЯДОК!)**
```sql
DELETE FROM person_order
WHERE order_date = '2022-02-25';
```

**Что удаляется:**
Все заказы, сделанные 25 февраля 2022 года.
Это 9 заказов из задания 12 (все люди заказали greek pizza).

**Почему СНАЧАЛА person_order:**
Из-за FOREIGN KEY constraint!

В таблице person_order есть внешний ключ:
```sql
fk_order_menu_id: menu_id → menu(id)
```

Это значит: заказ ссылается на пиццу в меню.

**FOREIGN KEY запрещает:**
Удалять пиццу из menu, пока на неё ссылаются заказы.

**Если бы сделали наоборот:**
```
1. DELETE FROM menu WHERE pizza_name = 'greek pizza';
   ❌ ERROR: update or delete on table "menu" violates 
             foreign key constraint "fk_order_menu_id"
   ❌ DETAIL: Key (id)=(19) is still referenced from 
             table "person_order"

2. DELETE FROM person_order ...
   ❌ Не выполнится, потому что первый DELETE упал
```

**Правильный порядок:**
```
1. DELETE person_order ✅ (освобождает ссылки на menu.id=19)
2. DELETE menu ✅ (теперь можно безопасно удалить)
```

**Правило:** Всегда удаляем зависимые данные ДО главных!

### **Шаг 2: DELETE menu**
```sql
DELETE FROM menu
WHERE pizza_name = 'greek pizza';
```

**Что удаляется:**
Greek pizza из меню (id=19, price=720₽).
Это откатывает:
- Задание 07: INSERT greek pizza с ценой 800₽
- Задание 11: UPDATE цены до 720₽

**Почему можно удалить:**
На предыдущем шаге удалили все заказы на эту пиццу.
Теперь на menu.id=19 нет ссылок → можно безопасно удалить.

### **Шаг 3 и 4: SELECT (проверки)**
```sql
SELECT COUNT(*) = 0 AS orders_deleted
FROM person_order
WHERE order_date = '2022-02-25';
```

**Проверяем:**
- COUNT(*) подсчитывает оставшиеся заказы от 25.02
- = 0 сравнивает с нулём
- TRUE (t) если все удалены ✅

Аналогично для greek pizza.

### **Важные детали:**

**1. Иерархия зависимостей:**
```
menu (главная таблица)
  ↑
  └── person_order (зависимая, ссылается на menu)
```

Порядок удаления: снизу вверх (от зависимых к главным).

**2. Tombstone-маркеры:**
DELETE не удаляет данные физически сразу!
- Строки помечаются как "мёртвые" (Tombstone 🪦)
- Физическое удаление выполнит VACUUM позже

**3. Идемпотентность:**
Скрипт можно запускать многократно:
- 1-й запуск: удалит 9 заказов + 1 пиццу
- 2-й запуск: удалит 0 заказов + 0 пицц (уже удалены)
- Проверки всегда вернут TRUE

**4. Что НЕ откатывается:**
Этот скрипт удаляет только:
- Заказы от 25.02.2022 (задание 12)
- Greek pizza (задания 07, 11)

НЕ удаляется:
- Sicilian pizza (задание 08)
- Посещения Denis и Irina (задание 09)
- Заказы на sicilian pizza (задание 10)

**5. Каскадное удаление (если бы было):**
Если бы FOREIGN KEY был настроен с ON DELETE CASCADE:
```sql
FOREIGN KEY (menu_id) REFERENCES menu(id) ON DELETE CASCADE
```

Тогда достаточно было бы:
```sql
DELETE FROM menu WHERE pizza_name = 'greek pizza';
```
И заказы удалились бы автоматически.

Но в нашей базе используется ON DELETE RESTRICT (по умолчанию),
поэтому нужно явно удалять в правильном порядке.
