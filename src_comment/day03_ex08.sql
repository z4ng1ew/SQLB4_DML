используя ДИНАМИЧЕСКИЕ значения (подзапросы) вместо хардкода.

**Отличие от Задания 07:**
- Задание 07: фиксированные значения (id=19, pizzeria_id=2)
- Задание 08: вычисляемые значения (MAX(id)+1, подзапрос для pizzeria_id)

**Структура скрипта (4 шага):**

### **Шаг 1: DELETE person_order (КРИТИЧНО!)**
```sql
DELETE FROM person_order
WHERE menu_id IN (SELECT id FROM menu WHERE pizza_name = 'sicilian pizza' ...);
```

**ПОЧЕМУ СНАЧАЛА УДАЛЯЕМ ЗАКАЗЫ:**
В PostgreSQL есть FOREIGN KEY constraint:
- person_order.menu_id → menu.id

Это означает: нельзя удалить пиццу из menu, если на неё есть заказы!

Если попытаться удалить menu БЕЗ удаления заказов:
```
ERROR: update or delete on table "menu" violates foreign key constraint
```

**Порядок обязательный:**
1. Сначала удаляем зависимые данные (person_order)
2. Потом удаляем главную таблицу (menu)

### **Шаг 2: DELETE menu**
```sql
DELETE FROM menu
WHERE pizza_name = 'sicilian pizza'
  AND pizzeria_id = (SELECT id FROM pizzeria WHERE name = 'Dominos');
```

**Зачем:**
Идемпотентность — можно запускать скрипт многократно без ошибок.

**Почему два условия (pizza_name И pizzeria_id):**
Может быть несколько пиццерий с sicilian pizza. Удаляем только из Dominos.

### **Шаг 3: INSERT с подзапросами**
```sql
INSERT INTO menu VALUES (
    (SELECT MAX(id) + 1 FROM menu),  -- Динамический ID
    (SELECT id FROM pizzeria WHERE name = 'Dominos'),  -- Динамический pizzeria_id
    'sicilian pizza',
    900
);
```

**Подзапрос 1: (SELECT MAX(id) + 1 FROM menu)**
- Находит максимальный существующий ID
- Добавляет 1 → получаем следующий свободный ID
- Адаптируется к текущему состоянию базы

**Подзапрос 2: (SELECT id FROM pizzeria WHERE name = 'Dominos')**
- Получает ID пиццерии по названию
- Не зависит от конкретного числа
- Более читаемо и переносимо

**Преимущества подзапросов:**
- Не нужно знать точные ID
- Работает в любой среде (dev, test, prod)
- Код самодокументируется

### **Шаг 4: SELECT (проверка)**
```sql
SELECT COUNT(*) = 1 AS is_single_record
FROM menu
WHERE pizza_name = 'sicilian pizza'
  AND pizzeria_id = (SELECT id FROM pizzeria WHERE name = 'Dominos')
  AND price = 900;
```

**Проверяем:**
1. Запись существует
2. Существует РОВНО ОДНА такая запись (не дубликаты)
3. Все поля правильные

**Ожидаемый результат:**
```
is_single_record
----------------
t  ← TRUE = успешно
```

**Если FALSE:**
- 0 записей → INSERT не сработал
- >1 записи → есть дубликаты

### **Важные моменты:**

**1. Порядок DELETE критичен:**
person_order → menu (из-за FOREIGN KEY)

**2. Идемпотентность:**
Скрипт можно запускать многократно — результат одинаковый

**3. Подзапросы vs хардкод:**
Подзапросы делают код адаптивным и переносимым

**4. Связь с другими заданиями:**
- Задание 09: добавит посещения Dominos
- Задание 10: добавит заказы на sicilian pizza (будет ссылаться на menu.id из этого задания)
```

