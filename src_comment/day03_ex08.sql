# 🔢 Прямые числовые значения и Хардкод — простое объяснение

## 🎯 Что такое "прямые числовые значения" и "хардкод"?

**Это одно и то же!** Просто разные названия.

---

## 📝 Определение

### **Хардкод (hardcode) / Прямые числовые значения**

= Когда ты **прямо в коде пишешь конкретное число**, вместо того чтобы его **вычислить или получить из базы**

---

## 🍕 Примеры из твоих заданий

### **❌ ХАРДКОД (Задание 07) — ПЛОХО для задания 08**

```sql
INSERT INTO menu (id, pizzeria_id, pizza_name, price)
VALUES (19, 2, 'greek pizza', 800);
        ↑   ↑
        |   └── ХАРДКОД! Прямое числовое значение "2"
        |
        └────── ХАРДКОД! Прямое числовое значение "19"
```

**Что это значит:**
- Ты **вручную прописал** число `19` для ID
- Ты **вручную прописал** число `2` для pizzeria_id
- Ты **жёстко закодировал** эти значения в скрипт

**На русском языке:**
> "Вставь запись с ID=19 и pizzeria_id=2"

---

### **✅ БЕЗ ХАРДКОДА (Задание 08) — ХОРОШО**

```sql
INSERT INTO menu (id, pizzeria_id, pizza_name, price)
VALUES (
    (SELECT MAX(id) + 1 FROM menu),
    (SELECT id FROM pizzeria WHERE name = 'Dominos'),
    'sicilian pizza',
    900
);
```

**Что это значит:**
- Ты **НЕ написал** конкретное число для ID
- Ты **попросил базу вычислить** следующий ID через `MAX(id) + 1`
- Ты **попросил базу найти** ID пиццерии через подзапрос
- Нет жёстко закодированных чисел!

**На русском языке:**
> "Вставь запись с ID = (следующий свободный) и pizzeria_id = (ID пиццерии Dominos)"

---

## 🔍 Наглядное сравнение

```
┌──────────────────┬─────────────────┬──────────────────────────┐
│ Параметр         │ ХАРДКОД         │ БЕЗ ХАРДКОДА             │
│                  │ (Задание 07)    │ (Задание 08)             │
├──────────────────┼─────────────────┼──────────────────────────┤
│ id               │ 19              │ (SELECT MAX(id)+1 ...)   │
│                  │ ↑ Прямое число  │ ↑ Вычисляется            │
├──────────────────┼─────────────────┼──────────────────────────┤
│ pizzeria_id      │ 2               │ (SELECT id WHERE ...)    │
│                  │ ↑ Прямое число  │ ↑ Ищется в базе          │
└──────────────────┴─────────────────┴──────────────────────────┘
```

---

## 💡 Почему хардкод — это плохо?

### **Проблема 1: Не адаптируется к изменениям**

```sql
-- ХАРДКОД
INSERT INTO menu VALUES (19, 2, ...);
```

**Что если:**
- В базе уже есть ID=19? ❌ ERROR: duplicate key
- В базе максимальный ID уже 25? ❌ Вставится ID=19 (старое значение)
- Пиццерия Dominos теперь имеет ID=5? ❌ Вставится в неправильную пиццерию

---

### **Проблема 2: Непереносимо между средами**

У тебя три среды:
- **Dev** (разработка): Dominos имеет ID=2
- **Test** (тестирование): Dominos имеет ID=7
- **Production** (боевая): Dominos имеет ID=15

```sql
-- С ХАРДКОДОМ
INSERT INTO menu VALUES (19, 2, ...);
↑ Работает только в Dev! В Test и Production — неправильная пиццерия!

-- БЕЗ ХАРДКОДА
INSERT INTO menu VALUES (
    (SELECT MAX(id)+1 FROM menu),
    (SELECT id FROM pizzeria WHERE name='Dominos'),
    ...
);
↑ Работает везде! Автоматически найдёт правильный ID
```

---

### **Проблема 3: Нечитаемо**

```sql
-- ХАРДКОД
INSERT INTO menu VALUES (19, 2, ...);
                             ↑
                         Что это за "2"?
                         Откуда это число?
                         Что оно означает? 🤔

-- БЕЗ ХАРДКОДА
INSERT INTO menu VALUES (
    ...,
    (SELECT id FROM pizzeria WHERE name='Dominos'),
    ...
);
    ↑
Сразу понятно: "это ID пиццерии Dominos" ✅
```

