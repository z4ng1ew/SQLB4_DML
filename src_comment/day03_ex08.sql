## 📖 Словарь терминов

```
ХАРДКОД (hardcode, хардкодить)
= жёстко закодированное значение
= прямое числовое значение
= константа в коде
= фиксированное значение

Примеры хардкода:
VALUES (19, 2, 'text', 800)
        ↑   ↑         ↑
     хардкод хардкод  хардкод

Противоположность хардкоду:
= динамическое значение
= вычисляемое значение
= подзапрос

Примеры БЕЗ хардкода:
VALUES (
    (SELECT MAX(id)+1 FROM menu),     ← вычисляется
    (SELECT id FROM pizzeria ...),     ← ищется в базе
    'text',                            ← это не число, хардкод допустим
    900                                ← это из задания, хардкод допустим
)
```

---

## 🎯 Что требует задание 08?

**Цитата из задания:**

> "**Не используй прямые числовые значения** для идентификаторов Primary key и pizzeria"

**Расшифровка:**

```
❌ НЕЛЬЗЯ:
VALUES (19, 2, ...)
        ↑   ↑
    Прямые числовые значения!

✅ МОЖНО:
VALUES (
    (SELECT MAX(id)+1 FROM menu),        ← Не прямое число, а подзапрос
    (SELECT id FROM pizzeria ...),       ← Не прямое число, а подзапрос
    'sicilian pizza',                    ← Это НЕ число, можно хардкодить
    900                                  ← Это цена из задания, можно хардкодить
)
```

---

## ✅ Что можно хардкодить в задании 08?

```sql
INSERT INTO menu (id, pizzeria_id, pizza_name, price)
VALUES (
    (SELECT ...),           ← НЕЛЬЗЯ хардкодить ID
    (SELECT ...),           ← НЕЛЬЗЯ хардкодить pizzeria_id
    'sicilian pizza',       ← МОЖНО! Это название из задания
    900                     ← МОЖНО! Это цена из задания
);
```

**Правило:**
- ❌ Не хардкодь ID и pizzeria_id (они могут меняться)
- ✅ Хардкодь название и цену (это из условия задания)

