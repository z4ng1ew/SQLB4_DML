-- ============================================================================
-- ПОДЗАПРОС 1: Вычисление ID
-- ============================================================================
-- (SELECT MAX(id) + 1 FROM menu)
--
-- ЛОГИКА:
-- 1. MAX(id) находит максимальный существующий ID в таблице menu
--    Пример: если есть id {1, 2, 3, ..., 18, 19}, то MAX(id) = 19
--
-- 2. MAX(id) + 1 добавляет 1
--    Результат: 19 + 1 = 20
--
-- 3. Этот результат используется как новый ID
--    INSERT ... VALUES (20, ...)
--
-- ПРЕИМУЩЕСТВА:
-- ✅ Автоматически адаптируется к текущему состоянию базы
-- ✅ Не нужно знать, какой ID следующий
-- ✅ Работает даже если в базу добавили другие записи
--
-- СРАВНЕНИЕ С ЗАДАНИЕМ 07:
-- Задание 07: VALUES (19, ...)        ← Хардкод
-- Задание 08: VALUES ((SELECT MAX(id)+1 FROM menu), ...) ← Динамика
--
-- ВАЖНО:
-- Этот подход НЕ гарантирует отсутствие конфликтов в многопоточной среде
-- (два одновременных INSERT могут получить одинаковый MAX(id)+1)
-- В production лучше использовать SEQUENCE или SERIAL

