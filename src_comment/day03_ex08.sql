-- 1. pizza_name = 'sicilian pizza'  → Правильное название
-- 2. pizzeria_id = (подзапрос)      → Правильная пиццерия (Dominos)
-- 3. price = 900                    → Правильная цена

-- ЛОГИКА COUNT(*) = 1:
-- - COUNT(*) подсчитывает количество строк
-- - = 1 создаёт булево условие:
--   * TRUE (t) если найдена ровно 1 запись  ✅
