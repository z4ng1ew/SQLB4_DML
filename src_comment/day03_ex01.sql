## 🔍 Сравнение с другими операторами множеств

```sql
-- ============================================================================
-- ОПЕРАТОРЫ ТЕОРИИ МНОЖЕСТВ В SQL
-- ============================================================================

/*
 * PostgreSQL поддерживает 3 оператора работы с множествами:
 * 
 * 1. UNION / UNION ALL     — Объединение множеств (A ∪ B)
 * 2. INTERSECT / INTERSECT ALL — Пересечение множеств (A ∩ B)
 * 3. EXCEPT / EXCEPT ALL   — Вычитание множеств (A \ B)
 */

-- ----------------------------------------------------------------------------
-- Пример данных для демонстрации:
-- ----------------------------------------------------------------------------
-- menu.id:          {1, 2, 3, 4, 5, 10}
-- person_order.menu_id: {1, 2, 3, 4}

-- ----------------------------------------------------------------------------
-- 1. UNION — объединение (все уникальные элементы из обоих множеств)
-- ----------------------------------------------------------------------------
SELECT id AS menu_id FROM menu
UNION
SELECT menu_id FROM person_order;
-- Результат: {1, 2, 3, 4, 5, 10} — все уникальные ID

-- ----------------------------------------------------------------------------
-- 2. INTERSECT — пересечение (только общие элементы)
-- ----------------------------------------------------------------------------
SELECT id AS menu_id FROM menu
INTERSECT
SELECT menu_id FROM person_order;
-- Результат: {1, 2, 3, 4} — только заказанные позиции, которые есть в меню

-- ----------------------------------------------------------------------------
-- 3. EXCEPT — вычитание (элементы из первого, которых нет во втором)
-- ----------------------------------------------------------------------------
SELECT id AS menu_id FROM menu
EXCEPT
SELECT menu_id FROM person_order;
-- Результат: {5, 10} — незаказанные позиции (НАША ЗАДАЧА)

-- ----------------------------------------------------------------------------
-- ОБРАТНОЕ EXCEPT (поменяли местами)
-- ----------------------------------------------------------------------------
SELECT menu_id FROM person_order
EXCEPT
SELECT id AS menu_id FROM menu;
-- Результат: {} — заказанных позиций, которых нет в меню (сломанные данные)
-- Если база корректна, результат пустой

-- ============================================================================
```

