-- Первый SELECT вернёт: {1, 2, 3, 4, 5, 10, 15}
-- Второй SELECT вернёт: {1, 2, 3, 4} (дубликаты автоматически убираются)
-- EXCEPT вычтет: {1, 2, 3, 4, 5, 10, 15} - {1, 2, 3, 4} = {5, 10, 15}
-- ORDER BY 1 упорядочит: {5, 10, 15}
--
-- Результат:
-- | menu_id |
-- |---------|
-- | 5       |
-- | 10      |
-- | 15      |
-- ============================================================================
