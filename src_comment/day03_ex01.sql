## Объяснение запроса для защиты

**Задача:**
Найти все позиции меню, которые никто никогда не заказывал.

**Ограничение:**
Нельзя использовать JOIN-операции.

**Решение через EXCEPT:**

1. **Первый SELECT** — получаю ВСЕ идентификаторы из таблицы menu
   - Это множество A: все доступные позиции

2. **EXCEPT** — оператор вычитания множеств из теории множеств
   - Математически: A \ B (A минус B)
   - Убирает из первого множества элементы, которые есть во втором

3. **Второй SELECT** — получаю идентификаторы, которые БЫЛИ заказаны
   - Это множество B: заказанные позиции
   - EXCEPT автоматически убирает дубликаты (если menu_id=1 заказали 10 раз, 
     он всё равно появится только один раз)

4. **Результат** — остаются только те ID, которых НЕТ в заказах
   - A - B = незаказанные позиции

5. **ORDER BY 1** — сортировка по первой колонке (menu_id)

**Почему EXCEPT, а не другие операторы?**
- NOT IN может работать некорректно с NULL
- NOT EXISTS требует коррелированный подзапрос (сложнее)
- LEFT JOIN запрещён по условию задания
- EXCEPT — самый простой и понятный способ для операции вычитания множеств

**Важная деталь:**
Порядок имеет значение! "A EXCEPT B" показывает элементы из A, которых нет в B.
Если поменять местами ("B EXCEPT A"), получим другой результат — позиции, 
которые заказывали, но которых нет в меню (сломанные данные).
```

