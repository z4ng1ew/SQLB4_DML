## 🎓 Для защиты

**Вопрос:** Что делает SET в SQL?

**Твой ответ:**

> "SET — это обязательная часть команды UPDATE, которая указывает, КАКУЮ колонку нужно изменить и НА КАКОЕ значение.
>
> Структура: `UPDATE таблица SET колонка = значение WHERE условие`
>
> Без SET команда UPDATE не будет работать — PostgreSQL не поймёт, что именно нужно изменить.
>
> В моём примере: `SET price = 800` означает 'установи значение колонки price равным 800'.
>
> SET может изменять несколько колонок одновременно, разделяя их запятыми: `SET price = 800, pizza_name = 'new name'`"

---

## 💡 Краткая шпаргалка

```
UPDATE = команда "обнови"
SET = ключевое слово "установи/измени"

Структура:
UPDATE table
SET column = value
WHERE condition;

Примеры:
SET price = 800              ← Прямое значение
SET price = price * 0.9      ← Выражение
SET price = (SELECT ...)     ← Подзапрос
SET col1 = val1, col2 = val2 ← Несколько колонок

Правило:
✅ UPDATE всегда требует SET
❌ UPDATE без SET = синтаксическая ошибка
```

