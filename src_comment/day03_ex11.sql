WHERE pizza_name = 'greek pizza';
-- Формула: 800 - 800*0.1 = 800 - 80 = 720₽
-- Эквивалентно: price * 0.9

-- Шаг 3: Проверка корректности
SELECT (800 - 800 * 0.1) = price AS price_reduced_by_10_percent
FROM menu
WHERE pizza_name = 'greek pizza';
-- Проверяем: 720 = price? → TRUE (t)
-- Ожидаемый результат: price_reduced_by_10_percent = t

-- ============================================================================
-- КЛЮЧЕВЫЕ МОМЕНТЫ:
-- - Два UPDATE обеспечивают идемпотентность (можно запускать многократно)
-- - Формула уменьшения: price - price*0.1 = price*0.9
-- - Финальная цена: 800₽ → 720₽ (скидка 80₽)
-- ============================================================================
