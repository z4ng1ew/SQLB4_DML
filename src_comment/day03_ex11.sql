--
-- Пользователь видит только живую строку (price=720)
-- Но физически в базе остаются обе версии до VACUUM

-- ============================================================================
-- ШАГ 3: Проверка корректности изменения
-- ============================================================================

SELECT (800 - 800 * 0.1) = price AS price_reduced_by_10_percent
FROM menu
WHERE pizza_name = 'greek pizza';

