# 🔧 SET — что это за команда?

## 🎯 Простой ответ

**SET** = **"установи"** или **"измени на"**

Это **НЕ отдельная команда**, а **обязательная часть команды UPDATE**!

---

## 📝 Структура команды UPDATE

```sql
UPDATE таблица
SET колонка = новое_значение
WHERE условие;
```

**Разбор:**

```sql
UPDATE menu              ← "Обнови таблицу menu"
SET price = 800          ← "УСТАНОВИ цену равной 800"
WHERE pizza_name = ...   ← "Где название пиццы = ..."
```

---

## 💡 Что делает SET?

**SET** указывает **ЧТО ИМЕННО** нужно изменить и **НА ЧТО**.

```sql
SET колонка = значение
    ───┬───   ───┬───
       │         └─── На что меняем
       │
       └───────────── Что меняем
```

---

## 🍕 Твой пример

### **Пример 1:**

```sql
UPDATE menu
SET price = 800
    ─────┬─────
         │
    "Установи price равным 800"
WHERE pizza_name = 'greek pizza';
```

**На русском языке:**
> "Обнови таблицу menu: **установи** price = 800 для greek pizza"

---

### **Пример 2:**

```sql
UPDATE menu
SET price = price - price * 0.1
    ─────┬─────────────────────
         │
    "Установи price равным (текущая цена минус 10%)"
WHERE pizza_name = 'greek pizza';
```

**На русском языке:**
> "Обнови таблицу menu: **установи** price = price * 0.9 для greek pizza"

---

## 🔄 SET — обязательная часть UPDATE

### **❌ БЕЗ SET — ошибка:**

```sql
UPDATE menu
price = 800                -- ❌ Где SET?
WHERE pizza_name = 'greek pizza';

-- ERROR: syntax error at or near "price"
```

PostgreSQL не понимает, что делать! Нет ключевого слова SET.

---

### **✅ С SET — работает:**

```sql
UPDATE menu
SET price = 800            -- ✅ Есть SET!
WHERE pizza_name = 'greek pizza';
```

PostgreSQL понимает: "Ага, нужно УСТАНОВИТЬ price = 800"

