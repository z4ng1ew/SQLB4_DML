## Объяснение скрипта для защиты

**Задача:**
Уменьшить цену на greek pizza на 10% от текущего значения.

**Структура скрипта (3 шага):**

### **Шаг 1: UPDATE #1 (нормализация)**
```sql
UPDATE menu
SET price = 800
WHERE pizza_name = 'greek pizza' AND price != 800;
```

**Зачем этот UPDATE:**
Обеспечивает идемпотентность — возможность запускать скрипт многократно
с одинаковым результатом.

**Проблема без него:**
```
1-й запуск: 800₽ * 0.9 = 720₽ ✅
2-й запуск: 720₽ * 0.9 = 648₽ ❌ Неправильно!
3-й запуск: 648₽ * 0.9 = 583₽ ❌ Еще хуже!
```

**С нормализацией:**
```
1-й запуск: 800₽ → 800₽ * 0.9 = 720₽ ✅
2-й запуск: 720₽ → 800₽ → 800₽ * 0.9 = 720₽ ✅
3-й запуск: 720₽ → 800₽ → 800₽ * 0.9 = 720₽ ✅
```

Каждый раз возвращаем цену к базовой 800₽, затем применяем скидку.

### **Шаг 2: UPDATE #2 (применение скидки)**
```sql
UPDATE menu
SET price = price - price * 0.1
WHERE pizza_name = 'greek pizza';
```

**Формула уменьшения на 10%:**
```
price - price * 0.1
= price * (1 - 0.1)
= price * 0.9
```

**Вычисление:**
```
Исходная цена: 800₽
10% от цены: 800 * 0.1 = 80₽
Финальная цена: 800 - 80 = 720₽
```

**Альтернативные записи (эквивалентны):**
- `price * 0.9`
- `price - price * 0.1`
- `price * (1 - 0.1)`

### **Шаг 3: SELECT (проверка)**
```sql
SELECT (800 - 800 * 0.1) = price AS price_reduced_by_10_percent
FROM menu
WHERE pizza_name = 'greek pizza';
```

**Что проверяем:**
- Левая часть: (800 - 800 * 0.1) = 720 (ожидаемая цена)
- Правая часть: price (реальная цена в базе)
- Сравнение: 720 = price?

**Ожидаемый результат:**
```
price_reduced_by_10_percent = t (TRUE)
```

Означает, что цена корректно уменьшена до 720₽.

### **Важные детали:**

**1. Tombstone-маркеры (из теории):**
UPDATE не изменяет строку напрямую!
Внутри PostgreSQL:
1. Старая строка (price=800) помечается как "мёртвая" (Tombstone 🪦)
2. Создаётся новая строка (price=720)

Поэтому UPDATE = DELETE + INSERT (как в начале проекта было написано).

**2. Почему два UPDATE:**
- UPDATE #1: Подготовка (нормализация к 800₽)
- UPDATE #2: Выполнение задания (скидка 10%)

Можно было сделать одним UPDATE:
```sql
UPDATE menu SET price = 800 * 0.9 WHERE pizza_name = 'greek pizza';
```
Но наш вариант более явный и показывает двухэтапный процесс.

**3. Производительность:**
Каждый UPDATE создаёт Tombstone-маркер.
Два UPDATE = два Tombstone-маркера = больше мусора.
Нужен регулярный VACUUM для очистки.

**4. Влияние на другие таблицы:**
UPDATE меняет только price, не меняет id.
Существующие заказы (person_order) не затрагиваются,
так как они ссылаются на menu.id, который остался прежним.
```

