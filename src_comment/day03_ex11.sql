-- ОПИСАНИЕ ПОДХОДА:
-- 1. UPDATE #1: Нормализуем цену greek pizza до базового значения 800₽
-- 2. UPDATE #2: Уменьшаем цену на 10% (умножаем на 0.9)
-- 3. SELECT: Проверяем, что цена корректно уменьшена до 720₽
--
-- КОНТЕКСТ:
-- Задание 07: Добавили greek pizza с ценой 800₽
-- Задание 11: Уменьшаем цену на 10% → финальная цена 720₽
--
-- ИДЕМПОТЕНТНОСТЬ: Скрипт можно запускать многократно

-- ============================================================================
-- ШАГ 1: Нормализация цены (подготовка для идемпотентности)
-- ============================================================================

UPDATE menu
SET price = 800
WHERE pizza_name = 'greek pizza'
  AND price != 800;

-- ЗАЧЕМ ЭТОТ UPDATE:
-- Обеспечивает идемпотентность скрипта - возвращает цену к исходному
-- значению 800₽ перед применением скидки 10%
--
-- БЕЗ ЭТОГО UPDATE:
-- 1-й запуск: 800₽ → 800₽ * 0.9 = 720₽ ✅
-- 2-й запуск: 720₽ → 720₽ * 0.9 = 648₽ ❌ Неправильно!
-- 3-й запуск: 648₽ → 648₽ * 0.9 = 583.2₽ ❌ Еще хуже!
--
-- С ЭТИМ UPDATE:
-- 1-й запуск: price != 800? Нет → не меняем → 800₽ → 800*0.9 = 720₽ ✅
-- 2-й запуск: price != 800? Да (720₽) → устанавливаем 800₽ → 800*0.9 = 720₽ ✅
-- 3-й запуск: price != 800? Да (720₽) → устанавливаем 800₽ → 800*0.9 = 720₽ ✅
-- Результат всегда одинаковый!

-- УСЛОВИЕ "price != 800":
-- Оптимизация: обновляем только если цена отличается от 800₽
-- - Если price = 800: ничего не делаем (уже правильная цена)
-- - Если price = 720, 900, 1000: устанавливаем 800₽

-- ВИЗУАЛИЗАЦИЯ:
-- ДО UPDATE #1 (если скрипт запускали раньше):
-- menu
-- ┌────┬─────────────┬──────────────┬───────┐
-- │ id │ pizzeria_id │ pizza_name   │ price │
-- ├────┼─────────────┼──────────────┼───────┤
-- │ 19 │ 2           │ greek pizza  │ 720   │ ← После предыдущего запуска
-- └────┴─────────────┴──────────────┴───────┘
--
-- ПОСЛЕ UPDATE #1:
-- ┌────┬─────────────┬──────────────┬───────┐
-- │ id │ pizzeria_id │ pizza_name   │ price │
-- ├────┼─────────────┼──────────────┼───────┤
-- │ 19 │ 2           │ greek pizza  │ 800   │ ← Нормализовано к базовой цене
-- └────┴─────────────┴──────────────┴───────┘

-- ============================================================================
-- ШАГ 2: Применение скидки 10%
-- ============================================================================

UPDATE menu
SET price = price - price * 0.1
WHERE pizza_name = 'greek pizza';

-- ФОРМУЛА УМЕНЬШЕНИЯ НА 10%:
-- price - price * 0.1
-- = price * (1 - 0.1)
-- = price * 0.9
--
-- Альтернативные способы записи:
-- SET price = price * 0.9              ← Короче
-- SET price = price - price * 0.1      ← Используется (более явно)
-- SET price = price * (1 - 0.1)        ← Математически эквивалентно

-- ПОШАГОВОЕ ВЫЧИСЛЕНИЕ:
-- Исходная цена: 800₽
-- 
-- Шаг 1: Вычисляем 10% от цены
-- price * 0.1 = 800 * 0.1 = 80
-- 
-- Шаг 2: Вычитаем из исходной цены
-- price - 80 = 800 - 80 = 720
-- 
-- Результат: 720₽

-- ПОЧЕМУ БЕЗ УСЛОВИЯ WHERE price != 720:
-- В этом UPDATE мы применяем скидку ко ВСЕМ greek pizza
-- без проверки текущей цены, потому что первый UPDATE
-- уже нормализовал цену до 800₽

-- ВИЗУАЛИЗАЦИЯ:
-- ДО UPDATE #2:
-- menu
-- ┌────┬─────────────┬──────────────┬───────┐
-- │ id │ pizzeria_id │ pizza_name   │ price │
-- ├────┼─────────────┼──────────────┼───────┤
-- │ 19 │ 2           │ greek pizza  │ 800   │
-- └────┴─────────────┴──────────────┴───────┘
--
-- ПОСЛЕ UPDATE #2:
-- ┌────┬─────────────┬──────────────┬───────┐
-- │ id │ pizzeria_id │ pizza_name   │ price │
-- ├────┼─────────────┼──────────────┼───────┤
-- │ 19 │ 2           │ greek pizza  │ 720   │ ← Скидка 10% применена
-- └────┴─────────────┴──────────────┴───────┘

-- TOMBSTONE-МАРКЕРЫ (из теории в начале проекта):
-- UPDATE не изменяет строку напрямую!
-- Реально происходит:
-- 1. Старая строка (price=800) помечается как "мёртвая" (Tombstone 🪦)
-- 2. Создаётся НОВАЯ строка (price=720)
-- 
-- Визуализация на уровне базы данных:
-- ┌────┬──────────────┬───────┬────────┐
-- │ id │ pizza_name   │ price │ Status │
-- ├────┼──────────────┼───────┼────────┤
-- │ 19 │ greek pizza  │ 800   │ 🪦 Dead│ ← Tombstone-маркер
-- │ 19 │ greek pizza  │ 720   │ ✓ Live │ ← Новая версия
