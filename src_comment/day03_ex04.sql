 * ОТВЕТ: Первый блок: женщины EXCEPT мужчины (только женщины).
 *        Второй блок: мужчины EXCEPT женщины (только мужчины).
 *        UNION объединяет оба типа "исключительных" пиццерий.
 * 
 * ВОПРОС 4: Что означает ORDER BY 1?
 * ОТВЕТ: Сортировка по первой колонке (pizzeria_name).
 *        Это то же самое, что ORDER BY pizzeria_name.
 * 
 * ВОПРОС 5: Может ли пиццерия попасть в результат дважды?
 * ОТВЕТ: Нет, невозможно. Если пиццерия попала в первую часть (только женщины),
 *        она не может попасть во вторую (только мужчины). UNION тоже убирает
 *        дубликаты, так что каждая пиццерия максимум 1 раз.
 * 
 * ВОПРОС 6: Что если пиццерию посещали и женщины, и мужчины?
 * ОТВЕТ: Пиццерия НЕ попадёт в результат. EXCEPT удалит её из обоих множеств,
 *        потому что она есть и у женщин, и у мужчин.
 * 
 * ВОПРОС 7: В чём разница между Заданием 03 и 04?
 * ОТВЕТ: Задание 03: person_visits + EXCEPT ALL + UNION ALL (дубликаты важны).
 *        Задание 04: person_order + EXCEPT + UNION (дубликаты не важны).
 *        03: "Чаще посещали", 04: "Только заказывали".
