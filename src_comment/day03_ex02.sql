-- КОММЕНТАРИЙ: Соединяем с таблицей menu для получения деталей
-- 
-- МЕХАНИЗМ РАБОТЫ:
-- 1. unordered_menu содержит: {menu_id: 5, 10, 15} (пример)
-- 2. menu содержит: {id, pizza_name, price, pizzeria_id}
