-- - pizza_name: название пиццы из таблицы menu
-- - price: цена пиццы из таблицы menu
-- - pizzeria_name: название пиццерии (алиас для pizz.name)

FROM (
    -- ========================================================================
    -- ПОДЗАПРОС: unordered_menu (незаказанные позиции меню)
    -- ========================================================================
    
    SELECT id AS menu_id
    -- ↑↑↑
    -- КОММЕНТАРИЙ: Берём все идентификаторы из таблицы menu
    -- - id: первичный ключ таблицы menu
    -- - AS menu_id: переименовываем для единообразия со вторым запросом EXCEPT
    
    FROM menu
    -- ↑↑↑
    -- КОММЕНТАРИЙ: Источник — таблица menu (справочник всех пицц)
    -- - Это множество A: ВСЕ доступные позиции меню
    
    EXCEPT
    -- ↑↑↑
    -- КОММЕНТАРИЙ: Оператор вычитания множеств (Set Difference)
    -- - Логика: A \ B = элементы из A, которых НЕТ в B
    -- - Здесь: Все menu.id МИНУС заказанные menu_id
    -- - Результат: ID пицц, которые никто не заказывал
