## 💡 Альтернативная версия с развёрнутыми комментариями

```sql
-- ============================================================================
--                          ДЕНЬ 03 | ЗАДАНИЕ 02
--            Незаказанные пиццы: названия, цены, пиццерии
-- ============================================================================

/*
 * КОНЦЕПЦИЯ ЗАПРОСА:
 * Этот запрос использует трёхуровневую архитектуру:
 * 
 * Уровень 1 (Подзапрос): Фильтрация — находим незаказанные menu_id
 * Уровень 2 (JOIN с menu): Обогащение — добавляем детали пиццы
 * Уровень 3 (JOIN с pizzeria): Обогащение — добавляем название ресторана
 * 
 * Это паттерн "Filter → Enrich → Present" в SQL
 */

-- ============================================================================
-- УРОВЕНЬ 3: Представление данных (SELECT)
-- ============================================================================

SELECT 
    pizza_name,              -- Что заказывали
    price,                   -- Сколько стоит
    pizz.name AS pizzeria_name  -- Где находится

-- ============================================================================
-- УРОВЕНЬ 1: Фильтрация (Подзапрос)
-- ============================================================================
-- Производная таблица (derived table) — результат вложенного SELECT

FROM (
    /*
     * ПОДЗАПРОС: Повторяет логику Задания 01
     * Находит menu_id, которые отсутствуют в person_order
     * 
     * ВИЗУАЛИЗАЦИЯ:
     * menu.id:           {1, 2, 3, 4, 5, 10, 11, ...}
     * person_order:      {1, 2, 3, 4, ...}
     * EXCEPT результат:  {5, 10, 11, ...}  ← незаказанные
     */
    
    SELECT id AS menu_id
    FROM menu
    
    EXCEPT
    
    SELECT menu_id
    FROM person_order
    
) AS unordered_menu  -- Обязательный алиас для подзапроса

/*
 * ПРОМЕЖУТОЧНЫЙ РЕЗУЛЬТАТ ПОДЗАПРОСА:
 * ┌─────────┐
 * │ menu_id │
 * ├─────────┤
 * │ 5       │
 * │ 10      │
 * │ 11      │
 * │ ...     │
 * └─────────┘
 */

-- ============================================================================
-- УРОВЕНЬ 2A: Обогащение деталями пиццы (JOIN с menu)
-- ============================================================================

INNER JOIN menu
    ON unordered_menu.menu_id = menu.id

/*
 * ЧТО ДАЁТ ЭТОТ JOIN:
 * Добавляет к menu_id дополнительные колонки:
 * - pizza_name: название пиццы
 * - price: цена
 * - pizzeria_id: ID пиццерии (для следующего JOIN)
 * 
 * ПРОМЕЖУТОЧНЫЙ РЕЗУЛЬТАТ:
 * ┌─────────┬───────────────┬───────┬─────────────┐
 * │ menu_id │ pizza_name    │ price │ pizzeria_id │
 * ├─────────┼───────────────┼───────┼─────────────┤
 * │ 5       │ cheese pizza  │ 950   │ 6           │
 * │ 10      │ cheese pizza  │ 780   │ 3           │
 * │ 11      │ supreme pizza │ 850   │ 3           │
 * └─────────┴───────────────┴───────┴─────────────┘
 */

-- ============================================================================
-- УРОВЕНЬ 2B: Обогащение названием пиццерии (JOIN с pizzeria)
-- ============================================================================

INNER JOIN pizzeria pizz
    ON pizz.id = menu.pizzeria_id

/*
 * ЧТО ДАЁТ ЭТОТ JOIN:
 * Заменяет pizzeria_id на человекочитаемое название
 * 
 * ФИНАЛЬНЫЙ РЕЗУЛЬТАТ (до сортировки):
 * ┌───────────────┬───────┬───────────────┐
 * │ pizza_name    │ price │ pizzeria_name │
 * ├───────────────┼───────┼───────────────┤
 * │ cheese pizza  │ 950   │ DinoPizza     │
 * │ cheese pizza  │ 780   │ DoDo Pizza    │
 * │ supreme pizza │ 850   │ DoDo Pizza    │
 * └───────────────┴───────┴───────────────┘
 */

-- ============================================================================
-- УРОВЕНЬ 3: Представление (Сортировка)
-- ============================================================================

ORDER BY 1, 2;  -- pizza_name ASC, price ASC

/*
 * ФИНАЛЬНЫЙ РЕЗУЛЬТАТ (после сортировки):
 * ┌───────────────┬───────┬───────────────┐
 * │ pizza_name    │ price │ pizzeria_name │
 * ├───────────────┼───────┼───────────────┤
 * │ cheese pizza  │ 700   │ Papa Johns    │  ← сначала дешевле
 * │ cheese pizza  │ 780   │ DoDo Pizza    │
 * │ cheese pizza  │ 950   │ DinoPizza     │
 * │ mushroom pizza│ 950   │ Papa Johns    │  ← следующее название
 * │ supreme pizza │ 850   │ DoDo Pizza    │
 * └───────────────┴───────┴───────────────┘
 */

-- ============================================================================
-- СРАВНЕНИЕ ПОДХОДОВ К РЕШЕНИЮ ЗАДАЧИ:
-- ============================================================================

/*
 * ПОДХОД 1 (наш): Подзапрос + JOIN
 * ✅ Переиспользует код из Задания 01
 * ✅ Логически структурирован
 * ⚠️ Может быть медленнее на больших данных
 * 
 * ПОДХОД 2: NOT EXISTS (без подзапроса)
 * 
 * SELECT m.pizza_name, m.price, p.name AS pizzeria_name
 * FROM menu m
 * INNER JOIN pizzeria p ON p.id = m.pizzeria_id
 * WHERE NOT EXISTS (
 *     SELECT 1 FROM person_order po WHERE po.menu_id = m.id
