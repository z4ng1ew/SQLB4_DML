-- КОММЕНТАРИЙ: Соединяем с таблицей pizzeria для получения названия
-- 
-- МЕХАНИЗМ РАБОТЫ:
-- 1. menu содержит: pizzeria_id (внешний ключ)
-- 2. pizzeria содержит: {id, name, rating}
-- 3. JOIN по условию: pizz.id = menu.pizzeria_id
-- 4. Результат: добавляется название пиццерии (pizz.name)
-- 
-- ПОТОК ДАННЫХ:
--   menu (pizzeria_id)  →  JOIN  →  pizzeria (id, name)
--   {1, 4, 2}           →  =     →  {1: Pizza Hut, 4: Papa Johns, 2: Dominos}
-- 
-- АЛИАС 'pizz':
-- - Короткое имя для удобства записи
-- - Избегает конфликта имён (если бы было несколько pizzeria)
-- - Улучшает читаемость: pizz.name вместо pizzeria.name

-- ============================================================================
-- ЧАСТЬ 4: СОРТИРОВКА РЕЗУЛЬТАТА
