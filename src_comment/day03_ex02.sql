   - Возвращает список ID: {5, 10, 11, ...}
   - Имеет алиас `unordered_menu` (обязательно в PostgreSQL)

2. **Первый INNER JOIN** — связываем с таблицей `menu`
   - Условие: unordered_menu.menu_id = menu.id
   - Получаем: pizza_name, price, pizzeria_id для незаказанных позиций

3. **Второй INNER JOIN** — связываем с таблицей `pizzeria`
   - Условие: menu.pizzeria_id = pizzeria.id
   - Получаем: название пиццерии вместо её ID

4. **ORDER BY 1, 2** — сортировка по названию пиццы и цене

**Почему подзапрос в FROM?**
Потому что EXCEPT возвращает набор данных (производную таблицу), который можно
использовать как источник данных для JOIN. Это стандартная техника построения
сложных запросов: сначала фильтруем нужные ID, потом обогащаем их данными.

**Почему INNER JOIN, а не LEFT?**
- Все menu_id из подзапроса гарантированно существуют в таблице menu
  (мы взяли их оттуда же через EXCEPT)
- Все pizzeria_id в menu ссылаются на реальные пиццерии (внешний ключ)
- Записей без совпадений быть не может, поэтому LEFT JOIN излишен

**Цепочка данных:**
Подзапрос (незаказанные ID) → menu (детали пиццы) → pizzeria (название ресторана)
```

