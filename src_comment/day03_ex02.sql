## 🎯 Ключевые моменты для защиты

### 1. **Подзапрос обязательно должен иметь алиас**
```sql
-- ❌ ОШИБКА
FROM (SELECT ...) 

-- ✅ ПРАВИЛЬНО
FROM (SELECT ...) AS unordered_menu
```

### 2. **Почему два INNER JOIN?**
- Первый: связать незаказанные ID с таблицей menu
- Второй: добавить название пиццерии

### 3. **Порядок JOIN имеет значение**
```sql
-- Нельзя сразу присоединить pizzeria:
FROM подзапрос 
INNER JOIN pizzeria  -- ❌ Нет связи! pizzeria.id != menu_id

-- Нужна промежуточная таблица menu:
FROM подзапрос
INNER JOIN menu      -- ✅ Получаем pizzeria_id
INNER JOIN pizzeria  -- ✅ Используем pizzeria_id
```

### 4. **Производная таблица (Derived Table)**
Подзапрос в FROM создаёт временную таблицу в памяти, которая используется в JOIN

